#!/usr/bin/env python3
"""Renders every repo's public-facing files from brand/brand.json and doctrine/positioning.json.

Usage:
  python3 brand/tools/sync_repos.py                  # write the lint reference in brand/repos/<name>/ (README.block.md, CONTRIBUTING.md, SECURITY.md: the lint reference)
  python3 brand/tools/sync_repos.py --apply PARENT   # also write into PARENT/<name>/ checkouts (the monorepo is PARENT/ultrastable)
The README block sits between `<!-- brand:start -->` and `<!-- brand:end -->`; text outside the markers is the repo's own and is kept.
A README without markers has its H1 line replaced by the block. Images are copied to assets/brand/ so they render in any repo.
"""
import argparse, json, pathlib, re, shutil

ROOT = pathlib.Path(__file__).resolve().parents[2]
START, END = "<!-- brand:start (generated by brand/tools/sync_repos.py from brand/brand.json; edit that file) -->", "<!-- brand:end -->"
IMAGES = {"banner.png": "banner.png", "loop.png": "loop.png", "architecture.png": "architecture.png", "self-reference.png": "self-reference.png", "repo-map.png": "repo-map.png"}


def nav(cfg, current):
    parts = [f"**{r['name']}**" if r["name"] == current else f"[{r['name']}](https://github.com/{cfg['org']}/{r['name']})" for r in cfg["repos"] if r.get("status") != "retired"]  # DOCS-SYNC-1: retired repos are not navigation
    return " · ".join(parts)


def organized(cfg):
    """Plain-language 'How Ultrastable is organized', generated from brand/brand.json so it cannot drift from the manifest."""
    org = cfg["org"]
    live = [r for r in cfg["repos"] if r.get("status", "live") == "live" and r["name"] != ".github"]
    gone = [r for r in cfg["repos"] if r.get("status") == "retired"]
    st = cfg["structure"]
    rows = "\n".join(f"| [{r['name']}](https://github.com/{org}/{r['name']}) | {r.get('visibility', cfg['visibility'])} | {r['holds']} |" for r in live)
    rows += "".join(f"\n| [{t['name']}](https://github.com/{org}/{t['name']}) | {t['visibility']} | {t['line']} |" for t in cfg.get("tenants", []))
    old = "; ".join(f"[`{r['name']}`](https://github.com/{org}/{r['name']}) is now in `{r['moved_to']}`" for r in gone)
    pend = ", ".join(f"`{x['repo']}` into `{x['into']}` ({x['id']})" for x in st["pending"])
    pend_txt = f"Still to fold into the main repository: {pend}. " if st["pending"] else "Every code, specification and license repository is folded into the main one. "
    return f"""## How Ultrastable is organized
{st['rule']}

| Repository | Visibility | What it holds |
|---|---|---|
{rows}

The organization's profile page is [.github](https://github.com/{org}/.github). Retired, kept only so old links work: {old}. {pend_txt}The target set is {', '.join(f'`{t}`' for t in st['target'])}.
"""


def orgmap_js(cfg):
    st = cfg["structure"]
    live = [r for r in cfg["repos"] if r.get("status", "live") == "live" and r["name"] != ".github"]
    rows = [{"name": r["name"], "visibility": r.get("visibility", cfg["visibility"]), "holds": r["holds"]} for r in live]
    rows += [{"name": t["name"], "visibility": t["visibility"], "holds": t["line"]} for t in cfg.get("tenants", [])]
    data = {"org": cfg["org"], "rule": st["rule"], "target": st["target"], "pending": st["pending"], "repos": rows,
            "retired": [{"name": r["name"], "moved_to": r["moved_to"]} for r in cfg["repos"] if r.get("status") == "retired"]}
    return "// SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0\n// Generated by brand/tools/sync_repos.py from brand/brand.json (ORGMAP-1). Do not edit.\nexport default " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"


def block(cfg, pos, r):
    org, n = cfg["org"], r["name"]
    img = "assets/brand/"
    q = "\n".join(f"```sh\n{c}\n```" if " " in c and not c[0].isupper() else f"- {c}" for c in r["quickstart"])
    proof = "" if n == "ultrastable" else f"\nThe proof lives in [{org}/ultrastable](https://github.com/{org}/ultrastable): run `python3 -m foundation selfhost --verify` there. This repo is one of the parts it runs.\n"
    memrule = pos['memory']['rule'] if n == 'ultrastable' else pos['memory']['rule'].replace('this repository', f'the {org}/ultrastable repository')
    return f"""{START}
<p align="center"><img src="{img}banner.png" alt="ultrastable: {pos['tagline']}" width="100%"></p>

# {org}/{n}

**{pos['tagline']}**

{pos['autonomy']['tagline']}

{r['line']}

![visibility](https://img.shields.io/badge/repo-{cfg['visibility']}-12342A) ![license](https://img.shields.io/badge/license-USL--1.0%20source--available-FFC857) [![site](https://img.shields.io/badge/site-ultrastable.io-FF5B1F)]({cfg['site']})

**The organization:** {nav(cfg, n)} · [ultrastable.io]({cfg['site']})

## What it is
{r['line']} Ultrastable is an autonomous development platform: an organization of virtual managers and staff that runs projects, scores its own decisions, earns wider autonomy from its track record, and interrupts a person only for steps that cannot be undone.

<p align="center"><img src="{img}loop.png" alt="The loop every manager runs: predict, execute, verify, score, plus" width="90%"></p>

## Who it is for
{r['audience']}

## Quickstart
{q}

## It runs on itself
{pos['runs_on_itself']['line']}
{proof}

<p align="center"><img src="{img}self-reference.png" alt="Ultrastable runs on itself" width="80%"></p>

{organized(cfg)}
## License
{cfg['license']['summary']} Full terms: [{cfg['license']['name']}](https://github.com/{org}/ultrastable/blob/main/{cfg['license']['file']}). Commercial licensing: {cfg['contact']}.

## Memory
{memrule}

## Contribute and report
[CONTRIBUTING.md](CONTRIBUTING.md) · [SECURITY.md](SECURITY.md) · contact {cfg['contact']}
{END}"""


def contributing(cfg, pos, r):
    org = cfg["org"]
    return f"""# Contributing to {org}/{r['name']}

{pos['tagline']} Work here is done by people and agents under one operating agreement: [agents/AGENTS.md](https://github.com/{org}/ultrastable/blob/main/agents/AGENTS.md) in the system of record.

1. Start from an open issue (driver order in [ROADMAP.md](https://github.com/{org}/ultrastable/blob/main/ROADMAP.md)) and claim it.
2. Branch `agent/<item>-<slug>`; open a draft PR within minutes.
3. Every PR states what was verified and the evidence. Never review your own work; a review includes at least one plus.
4. {pos['memory']['rule']}
5. Contributions are licensed under the [{cfg['license']['name']}](https://github.com/{org}/ultrastable/blob/main/LICENSE), section 11 (DCO-style certification, licensed to everyone under the License, and to the Licensor for Commercial Licenses).
6. Commit titles follow [Conventional Commits 1.0.0](https://www.conventionalcommits.org/en/v1.0.0/), for example `fix(worker): retry merge on 502`.

Other repositories: {nav(cfg, r['name'])}.
"""


def security(cfg, pos, r):
    return f"""# Security policy for {cfg['org']}/{r['name']}

If you found a vulnerability in anything Ultrastable runs ({cfg['site']} or a pilot deployment), email **{cfg['security_contact']}** with the subject `SECURITY`. Include what you saw, where, and how to reproduce it.

- We acknowledge within two working days.
- Give us a reasonable window to fix before disclosing.
- Do not access data that is not yours and do not run denial-of-service tests.
- Never post secrets or exploit details in a public issue.

Where that mailbox is read: [docs/ops/CONTACT.md](https://github.com/{cfg['org']}/ultrastable/blob/main/docs/ops/CONTACT.md).
"""


def merge(existing, new):
    if START.split(" (")[0] in existing:
        return re.sub(r"<!-- brand:start.*?<!-- brand:end -->", lambda m: new, existing, flags=re.S)
    lines = existing.split("\n")
    i = next((k for k, l in enumerate(lines) if l.startswith("# ")), None)
    rest = lines[i + 1:] if i is not None else lines
    body = "\n".join(rest).strip("\n")
    return new + "\n\n" + body + "\n" if body else new + "\n"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply")
    ap.add_argument("--check", action="store_true", help="fail if brand/repos, README.md or site/orgmap.js are stale")
    a = ap.parse_args()
    cfg = json.loads((ROOT / "brand/brand.json").read_text())
    pos = json.loads((ROOT / "doctrine/positioning.json").read_text())
    gen = ROOT / "brand/generated"
    if a.check:
        bad = []
        for r in cfg["repos"]:
            f = ROOT / "brand/repos" / r["name"] / "README.block.md"
            if not f.exists() or f.read_text(encoding="utf-8") != block(cfg, pos, r) + "\n":
                bad.append(str(f.relative_to(ROOT)))
        rd = (ROOT / "README.md").read_text(encoding="utf-8")
        if organized(cfg) not in rd:
            bad.append("README.md (How Ultrastable is organized)")
        om = ROOT / "site/orgmap.js"
        if not om.exists() or om.read_text(encoding="utf-8") != orgmap_js(cfg):
            bad.append("site/orgmap.js")
        print("orgmap stale: " + ", ".join(bad) if bad else "orgmap current")
        raise SystemExit(1 if bad else 0)
    write(ROOT / "site/orgmap.js", orgmap_js(cfg))
    for r in cfg["repos"]:
        n = r["name"]
        out = ROOT / "brand/repos" / n
        write(out / "README.block.md", block(cfg, pos, r) + "\n")
        write(out / "CONTRIBUTING.md", contributing(cfg, pos, r))
        write(out / "SECURITY.md", security(cfg, pos, r))
        for d in ([pathlib.Path(a.apply) / n] if a.apply else []):
            rp = d / "README.md"
            old = rp.read_text(encoding="utf-8") if rp.exists() else f"# {n}\n"
            write(rp, merge(old, block(cfg, pos, r)))
            write(d / "CONTRIBUTING.md", contributing(cfg, pos, r))
            write(d / "SECURITY.md", security(cfg, pos, r))
            for src, dst in IMAGES.items():
                (d / "assets/brand").mkdir(parents=True, exist_ok=True)
                shutil.copy(gen / src, d / "assets/brand" / dst)
            shutil.copy(gen / "cards" / f"{n}.png", d / "assets/brand/social-card.png")
    print("synced", len(cfg["repos"]), "repos", "(applied)" if a.apply else "")


if __name__ == "__main__":
    main()
