export const TemplateGenerator = {
  generate(archetype, params) {
    // Router for the archetype
    const router = {
      'security-txt': () => this.securityTxt(params),
      'spf': () => this.spf(params),
      'dmarc': () => this.dmarc(params),
      'privacy-page': () => this.privacyPage(params)
    };
    const factory = router[archetype];
    return factory ? factory() : null;
  },

  securityTxt(domain) {
    return `Contact: mailto:admin@${domain}
Contact: https://${domain}
`;
  },

  spf(domain) {
    return `v=spf1 mx include:spf.${domain.split('.')[1] || domain} -all`;
  },

  dmarc(domain) {
    return `v=DMARC1; p=none; rua=mailto:dmarc@${domain};`;
  },

  privacyPage(domain) {
    return `<!DOCTYPE html>
<html>
<head><title>Privacy Policy</title></head>
<body>
<h1>Privacy Policy</h1>
<p>This site, ${domain}, is auto-generated by the TemplateGenerator archetype.</p>
</body>
</html>`;
  }
};
