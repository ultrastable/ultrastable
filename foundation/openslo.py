"""STANDARDS-FIRST-1: the essential variables in doctrine/ultrastability.json, published as OpenSLO v1 SLO documents
(slo/essential-variables.yaml), so any OpenSLO tool reads the same bounds the second loop acts on. Generated, never
hand-edited; `--check` fails when the file is out of step with the doctrine."""
from __future__ import annotations
import json, re
from pathlib import Path
import yaml

REPO = Path(__file__).resolve().parent.parent
SRC, OUT = "doctrine/ultrastability.json", "slo/essential-variables.yaml"


def _name(s):
    return re.sub(r"[^a-z0-9-]+", "-", s.lower()).strip("-")[:63]


def build(root=REPO):
    d = json.loads((Path(root) / SRC).read_text(encoding="utf-8"))
    docs = []
    for scope, body in sorted(d["scopes"].items()):
        for v in body.get("variables", []):
            objectives = []
            if v.get("min") is not None:
                objectives.append({"displayName": "at or above min", "op": "gte", "value": v["min"], "target": 1.0})
            if v.get("max") is not None:
                objectives.append({"displayName": "at or below max", "op": "lte", "value": v["max"], "target": 1.0})
            docs.append({
                "apiVersion": "openslo/v1", "kind": "SLO",
                "metadata": {"name": _name(f"{scope}-{v['id']}"), "displayName": v.get("name", v["id"])},
                "spec": {
                    "description": v.get("why", ""), "service": _name(scope),
                    "indicator": {"metadata": {"name": _name(f"{scope}-{v['id']}-sli")},
                                  "spec": {"thresholdMetric": {"metricSource": {"type": "ultrastable",
                                                                                 "spec": {"reading": v.get("reading", v["id"]), "unit": v.get("unit", "")}}}}},
                    "timeWindow": [{"duration": "1d", "isRolling": True}],
                    "budgetingMethod": "Occurrences", "objectives": objectives}})
    return "# generated by `python3 -m foundation openslo --apply` from doctrine/ultrastability.json; do not edit\n" + \
        yaml.safe_dump_all(docs, sort_keys=False)


def apply(root=REPO):
    p = Path(root) / OUT
    p.parent.mkdir(parents=True, exist_ok=True)
    new = build(root)
    if p.exists() and p.read_text(encoding="utf-8") == new:
        return False
    p.write_text(new, encoding="utf-8")
    return True


def check(root=REPO):
    p = Path(root) / OUT
    if not p.exists() or p.read_text(encoding="utf-8") != build(root):
        return [f"{OUT} is out of date; run `python3 -m foundation openslo --apply`"]
    bad = []
    for doc in yaml.safe_load_all(p.read_text(encoding="utf-8")):
        if doc.get("apiVersion") != "openslo/v1" or doc.get("kind") != "SLO" or not doc["spec"]["objectives"]:
            bad.append(f"{OUT}: {doc.get('metadata', {}).get('name')} is not a valid OpenSLO v1 SLO")
    return bad
