"""STANDARDS-1 (Rowan 2026-11-25: "Figure out what the standards are and apply them broadly."). Ultrastable is the foundation for any autonomous
system.

The system's own registers are rendered into the standard files other tools already read, so no adapter has to learn Ultrastable's formats:

  catalog-info.yaml   Backstage Software Catalog (backstage.io/v1alpha1): the system, every Worker as a Component, every store as a Resource,
                      every tenant as a System with its repository, and the public HTTP API, from doctrine/topology.json and doctrine/tenant-repos.json.
  sbom.cdx.json       CycloneDX 1.6 SBOM: every first-party package and every GitHub Action the workflows run, by pinned commit (package URL
                      pkg:github/...), so the supply chain is machine-readable. No timestamp: the file changes only when the supply chain changes.

  python3 -m foundation stdgen --gen     write both from the registers
  python3 -m foundation stdgen --check   fail when either is out of date with the registers (run in checks; --gen runs in REGEN-1)
"""
from __future__ import annotations
import argparse, glob, hashlib, json, re, sys, uuid
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CATALOG, SBOM = "catalog-info.yaml", "sbom.cdx.json"
HEADER = ("# Backstage Software Catalog descriptor (https://backstage.io/docs/features/software-catalog/descriptor-format).\n"
          "# Generated by `python3 -m foundation stdgen --gen` from doctrine/topology.json and doctrine/tenant-repos.json; do not edit by hand.\n")
ORG = "ultrastable"
STORE_TYPE = {"d1": "database", "kv": "key-value-store", "r2": "object-storage", "queues": "queue", "vectorize": "vector-database", "workflows": "workflow"}


def _load(root, rel):
    return json.loads((Path(root) / rel).read_text(encoding="utf-8"))


def _name(s: str) -> str:  # Backstage names: [a-z0-9A-Z-_.], max 63
    return re.sub(r"[^A-Za-z0-9_.-]", "-", s)[:63].strip("-")


# ---------- Backstage ----------
def entities(root=REPO) -> list[dict]:
    topo, ten = _load(root, "doctrine/topology.json"), _load(root, "doctrine/tenant-repos.json")
    owner = f"group:{ORG}"
    out = [
        {"apiVersion": "backstage.io/v1alpha1", "kind": "Group", "metadata": {"name": ORG, "description": "The Ultrastable organization: the fleet that runs every loop."},
         "spec": {"type": "organization", "children": []}},
        {"apiVersion": "backstage.io/v1alpha1", "kind": "System", "metadata": {"name": ORG, "title": "Ultrastable", "description": "Ultrastable is the foundation for any autonomous system.",
         "annotations": {"github.com/project-slug": "ultrastable/ultrastable"}, "links": [{"url": "https://ultrastable.io/", "title": "Site"}]},
         "spec": {"owner": owner, "domain": ORG}},
        {"apiVersion": "backstage.io/v1alpha1", "kind": "API", "metadata": {"name": "ultrastable-public-api", "description": "Public read API of ultrastable.io (OpenAPI 3.1)."},
         "spec": {"type": "openapi", "lifecycle": "production", "owner": owner, "system": ORG, "definition": {"$text": "https://ultrastable.io/openapi.json"}}},
    ]
    stores = {}
    for kind, rows in (topo.get("stores") or {}).items():
        for s in rows:
            stores[s["name"]] = kind
            out.append({"apiVersion": "backstage.io/v1alpha1", "kind": "Resource",
                        "metadata": {"name": _name(s["name"]), "description": s.get("what", ""), "tags": ["cloudflare", _name(kind).lower()]},
                        "spec": {"type": STORE_TYPE.get(kind, kind), "owner": owner, "system": ORG}})
    tenant_by_worker = {v.get("worker"): k for k, v in ten["tenants"].items() if v.get("worker")}
    for w in topo["workers"]:
        b = w.get("bindings") or {}
        deps = []
        for kind in ("d1", "kv", "r2", "vectorize", "queues_producer"):
            v = b.get(kind) or {}
            deps += [f"resource:{_name(x)}" for x in (v.values() if isinstance(v, dict) else v) if x in stores]
        deps += [f"component:{_name(x)}" for x in (b.get("services") or {}).values()]
        system = tenant_by_worker.get(w["id"], ORG)
        meta = {"name": _name(w["id"]), "description": w.get("role", ""), "tags": ["cloudflare-workers"]}
        ann = {}
        if w.get("main"):
            ann["backstage.io/source-location"] = f"url:https://github.com/ultrastable/ultrastable/tree/main/{w['main']}"
        if isinstance(w.get("source"), dict) and w["source"].get("repo"):
            ann["github.com/project-slug"] = w["source"]["repo"]
        if ann:
            meta["annotations"] = ann
        if w.get("routes"):
            meta["links"] = [{"url": "https://" + r, "title": r} for r in w["routes"]]
        spec = {"type": "service", "lifecycle": "production" if w.get("state") == "live" else "experimental", "owner": owner, "system": system}
        if deps:
            spec["dependsOn"] = sorted(set(deps))
        if w["id"] == "ultrastable-site":
            spec["providesApis"] = ["ultrastable-public-api"]
        out.append({"apiVersion": "backstage.io/v1alpha1", "kind": "Component", "metadata": meta, "spec": spec})
    for k, v in ten["tenants"].items():
        meta = {"name": _name(k), "description": v.get("why") or v.get("note") or f"Tenant system {k} running on Ultrastable.", "annotations": {"github.com/project-slug": v["repo"]}}
        if v.get("frontend"):
            meta["links"] = [{"url": v["frontend"], "title": "Front end"}]
        out.append({"apiVersion": "backstage.io/v1alpha1", "kind": "System", "metadata": meta, "spec": {"owner": owner, "domain": ORG}})
    out.insert(2, {"apiVersion": "backstage.io/v1alpha1", "kind": "Domain", "metadata": {"name": ORG, "description": "Every system that runs on Ultrastable."}, "spec": {"owner": owner}})
    return out


def _yaml(v, ind=0) -> str:
    """Block YAML for dicts, lists and scalars; strings are JSON-quoted, which is valid YAML 1.2."""
    pad = "  " * ind
    if isinstance(v, dict):
        if not v:
            return "{}"
        lines = []
        for k, x in v.items():
            key = k if re.fullmatch(r"[A-Za-z0-9_./-]+", k) else json.dumps(k)
            if isinstance(x, (dict, list)) and x:
                lines.append(f"{pad}{key}:\n{_yaml(x, ind + 1)}")
            else:
                lines.append(f"{pad}{key}: {_yaml(x, ind + 1)}")
        return "\n".join(lines)
    if isinstance(v, list):
        if not v:
            return "[]"
        lines = []
        for x in v:
            if isinstance(x, dict) and x:
                body = _yaml(x, ind + 1).split("\n")
                lines.append(f"{pad}- {body[0].lstrip()}")
                lines += body[1:]
            else:
                lines.append(f"{pad}- {_yaml(x, ind + 1)}")
        return "\n".join(lines)
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return "null"
    if isinstance(v, (int, float)):
        return json.dumps(v)
    return json.dumps(str(v), ensure_ascii=False)


def render_catalog(root=REPO) -> str:
    return HEADER + "".join("---\n" + _yaml(e) + "\n" for e in entities(root))


# ---------- CycloneDX ----------
USES = re.compile(r"^\s*-?\s*uses:\s*([^\s#@]+)@([0-9a-f]{40})\s*(?:#\s*(\S+))?", re.M)


def sbom(root=REPO) -> dict:
    root = Path(root)
    comps, seen = [], set()
    for f in sorted(glob.glob(str(root / "**/package.json"), recursive=True)):
        if "node_modules" in f:
            continue
        d = json.loads(Path(f).read_text(encoding="utf-8"))
        rel = Path(f).relative_to(root).parent.as_posix()
        name = d.get("name") or rel
        ref = f"pkg:npm/{name.replace('@', '%40')}" + (f"@{d['version']}" if d.get("version") else "")
        if ref in seen:
            continue
        seen.add(ref)
        c = {"type": "library", "bom-ref": ref, "name": name, "purl": ref, "scope": "required",
             "properties": [{"name": "ultrastable:path", "value": rel}, {"name": "ultrastable:third-party-dependencies", "value": str(len(d.get("dependencies") or {}))}]}
        if d.get("version"):
            c["version"] = d["version"]
        comps.append(c)
    for f in sorted(glob.glob(str(root / ".github/workflows/*.yml")) + glob.glob(str(root / "seed/.github/workflows/*.yml"))):
        for m in USES.finditer(Path(f).read_text(encoding="utf-8")):
            action, sha, tag = m.group(1), m.group(2), m.group(3)
            owner_repo = "/".join(action.split("/")[:2])
            ref = f"pkg:github/{owner_repo}@{sha}"
            if ref in seen:
                continue
            seen.add(ref)
            c = {"type": "application", "bom-ref": ref, "name": action, "version": sha, "purl": ref, "scope": "required",
                 "externalReferences": [{"type": "vcs", "url": f"https://github.com/{owner_repo}"}]}
            if tag:
                c["properties"] = [{"name": "ultrastable:tag-comment", "value": tag}]
            comps.append(c)
    comps.sort(key=lambda c: c["bom-ref"])
    body = {"bomFormat": "CycloneDX", "specVersion": "1.6", "version": 1,
            "metadata": {"component": {"type": "application", "bom-ref": "pkg:github/ultrastable/ultrastable", "name": "ultrastable",
                                       "purl": "pkg:github/ultrastable/ultrastable", "licenses": [{"license": {"id": "LicenseRef-Ultrastable-USL-1.0", "url": "https://github.com/ultrastable/license"}}]},
                         "tools": {"components": [{"type": "application", "name": "foundation stdgen", "group": "ultrastable"}]}},
            "components": comps}
    digest = hashlib.sha256(json.dumps(body, sort_keys=True).encode()).hexdigest()
    return {**body, "serialNumber": f"urn:uuid:{uuid.uuid5(uuid.NAMESPACE_URL, 'ultrastable-sbom:' + digest)}"}


def render_sbom(root=REPO) -> str:
    return json.dumps(sbom(root), indent=2) + "\n"


# ---------- CLI ----------
TARGETS = {CATALOG: render_catalog, SBOM: render_sbom}


def gen(root=REPO) -> list[str]:
    wrote = []
    for rel, fn in TARGETS.items():
        p, text = Path(root) / rel, fn(root)
        if not p.exists() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8")
            wrote.append(rel)
    return wrote


def check(root=REPO) -> list[str]:
    bad = []
    for rel, fn in TARGETS.items():
        p = Path(root) / rel
        if not p.exists() or p.read_text(encoding="utf-8") != fn(root):
            bad.append(f"{rel}: out of date with the registers; run `python3 -m foundation stdgen --gen`")
    return bad


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="foundation stdgen")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--gen", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    if a.gen:
        print("\n".join(gen()) or "stdgen: catalog-info.yaml and sbom.cdx.json current")
        return 0
    bad = check()
    print("\n".join(bad) or "stdgen ok: catalog-info.yaml (Backstage) and sbom.cdx.json (CycloneDX 1.6) match the registers")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
