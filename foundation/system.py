"""SYSTEM-1: the one running system as data, rendered to wrangler configs (owner directive 2026-11-12). Ultrastable is the foundation for any autonomous system.

  python3 -m foundation system --render    write instances/ultrastable/system/<worker>.wrangler.jsonc for every worker in doctrine/system.json
  python3 -m foundation system --check     rendered files match the data; every service binding names a worker; every queue has a producer and a consumer
Data: doctrine/system.json. Deploy: deploy/deploy-system.mjs (the same data).
"""
from __future__ import annotations
import json, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = "instances/ultrastable/system"


def load(root=REPO) -> dict:
    return json.loads((Path(root) / "doctrine/system.json").read_text(encoding="utf-8"))


def render_worker(d: dict, name: str) -> dict:
    w, b, res = d["workers"][name], d["workers"][name]["bindings"], d["resources"]
    c = {"name": name, "main": (w["main"] if w.get("source") else "../../../" + w["main"]),  # TENANT-REPO-1: a tenant config sits at its own repository root
         "compatibility_date": d["compatibility_date"], "workers_dev": False, "observability": {"enabled": True}}
    if w["crons"]:
        c["triggers"] = {"crons": w["crons"]}
    if b.get("d1"):
        c["d1_databases"] = [{"binding": k, "database_name": res["d1"][v]["name"], "database_id": res["d1"][v]["id"]} for k, v in b["d1"].items()]
    if b.get("ai"):
        c["ai"] = {"binding": b["ai"][0]}
    if b.get("kv"):
        c["kv_namespaces"] = [{"binding": k, "title": res["kv"][v]["title"]} for k, v in b["kv"].items()]
    if b.get("queue_producers") or b.get("queue_consumers"):
        c["queues"] = {"producers": [{"binding": k, "queue": res["queues"][v]["name"]} for k, v in b.get("queue_producers", {}).items()],
                       "consumers": [{"queue": res["queues"][q]["name"]} for q in b.get("queue_consumers", [])]}
    if b.get("vectorize"):
        c["vectorize"] = [{"binding": k, "index_name": res["vectorize"][v]["name"]} for k, v in b["vectorize"].items()]
    if b.get("services"):
        c["services"] = [{"binding": k, "service": v} for k, v in b["services"].items()]
    return c


def text(c: dict) -> str:
    return "// GENERATED by python3 -m foundation system --render from doctrine/system.json. Do not edit.\n" + json.dumps(c, indent=2) + "\n"


def render(root=REPO) -> list[str]:
    d, out = load(root), []
    (Path(root) / OUT).mkdir(parents=True, exist_ok=True)
    for n in d["workers"]:
        p = Path(root) / OUT / f"{n}.wrangler.jsonc"
        p.write_text(text(render_worker(d, n)), encoding="utf-8"); out.append(p.relative_to(root).as_posix())
    return out


def check(root=REPO) -> list[str]:
    root, d, bad = Path(root), load(root), []
    for n, w in d["workers"].items():
        p = root / OUT / f"{n}.wrangler.jsonc"
        if not p.is_file() or p.read_text(encoding="utf-8") != text(render_worker(d, n)):
            bad.append(f"{n}: rendered config missing or stale; run python3 -m foundation system --render")
        if not w.get("source") and not (root / w["main"]).is_file():
            bad.append(f"{n}: main {w['main']} does not exist")
        for k, s in w["bindings"].get("services", {}).items():
            if s not in d["workers"]:
                bad.append(f"{n}: service binding {k} names unknown worker {s}")
    prod = {v for w in d["workers"].values() for v in w["bindings"].get("queue_producers", {}).values()}
    cons = {q for w in d["workers"].values() for q in w["bindings"].get("queue_consumers", [])}
    for q in d["resources"]["queues"]:
        if q not in prod or q not in cons:
            bad.append(f"queue {q}: needs a producer and a consumer")
    return bad


def main(argv) -> int:
    if "--render" in argv:
        print("\n".join(render())); return 0
    bad = check()
    print("system ok" if not bad else "\n".join(bad))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
