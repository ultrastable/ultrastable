"""GENESIS-1: a new system is born with a backlog, a roadmap, a charter, a staffed team and an infra checklist.

Before this, `new-system` wrote roles and owner cards but no work list, so the managers had nothing to pick on their
first tick. Genesis derives, from the resolved manifest alone, (1) org/charter.md, (2) docs/issues/*.json (the backlog,
same shape the tick already reads), (3) ROADMAP.md (Now/Next/Later rendered from that backlog), (4) org/team.json (the
phased staff from doctrine/team.json + team.recommend) and (5) org/infra.json (what the chosen runtime needs, per adapter).
Porting is a backlog item, not a special case: every runtime in the adapter registry that is not the chosen one gets a
PORT-<id> item whose closing probe is the adapter's own `selfhost --verify` style command. Ultrastable porting itself to
another platform is therefore the system working its own generated backlog.
"""
from __future__ import annotations
import json
from pathlib import Path

from . import team

REPO = Path(__file__).resolve().parent.parent
PHASE_MILESTONE = {0: "Now", 1: "Next", 2: "Later"}

# What each runtime must provide before the tick can ring. The names are the adapter-neutral roles of the platform.
INFRA = {
    "cloudflare": [("clock", "Worker cron trigger (*/10 * * * *)"), ("store", "D1 database for items, claims, trust"), ("executor", "GitHub Actions job rung by the Worker"), ("dashboard", "Worker route serving the dashboard"), ("secrets", "Worker secrets, names only in repo")],
    "gcp": [("clock", "Cloud Scheduler job to Cloud Run"), ("store", "Firestore or Cloud SQL"), ("executor", "Cloud Run job"), ("dashboard", "Cloud Run service"), ("secrets", "Secret Manager, names only in repo")],
    "self-hosted": [("clock", "OS scheduler or `python3 -m foundation launch` loop"), ("store", "SQLite file (platform/adapters/sqlite)"), ("executor", "local process"), ("dashboard", "`python3 scripts/self_dashboard.py`"), ("secrets", "environment, names only in repo")],
}


def _item(iid: str, title: str, ws: str, role: str, milestone: str, done: str, trigger: str = "tick") -> dict:
    return {"id": iid, "title": f"{iid}: {title}",
            "body": f"**Owner:** {role}\n**Trigger:** {trigger}\n**Done check:** {done}\n**Status:** open\n\nSeeded by GENESIS-1. Every closed item proposes a plus: file it as a new issue labeled `plus`.",
            "labels": [f"role:{role}", f"ws:{ws}"], "milestone": milestone, "workstream": ws.title()}


def runtimes() -> list[str]:
    from .manifest import RUNTIMES
    return sorted(RUNTIMES)


def backlog(m: dict, root: Path = REPO) -> list[dict]:
    items: list[dict] = []
    prov = m["runtime"]["provider"]
    items.append(_item("GEN-1", "Arm the clock: first tick runs and writes evidence", "platform", "operations", "Now", "ops/loop-evidence/ has a row from this instance's tick"))
    for i, (part, what) in enumerate(INFRA[prov], 1):
        items.append(_item(f"INF-{i}", f"{prov} {part}: {what}", "platform", "operations", "Now", f"org/infra.json {part} status is live; probe recorded"))
    for i, g in enumerate(m["goals"], 1):
        items.append(_item(f"GOAL-{i}", g, "product", "product-manager", "Now", "a measurable outcome is recorded against the goal"))
    rec = team.recommend(m, root)
    for n in (0, 1, 2):
        for rid in rec[f"phase_{n}"]:
            items.append(_item(f"STAFF-{rid}", f"Onboard {rid}: first deliverable in docs/handoff/{rid}.md", "staff", "portfolio-manager", PHASE_MILESTONE[n],
                               f"file:docs/handoff/{rid}.md exists" if n else "role has run one tick with evidence", trigger=f"phase {n} gate"))
    for other in runtimes():
        if other != prov:
            items.append(_item(f"PORT-{other}", f"Port this system to {other}: adapter, deploy path and a green selfhost-style verify", "platform", "staff", "Later",
                               f"adapter registered in platform/adapters/registry.json and its verify command passes on {other}", trigger="phase 2 gate"))
    items.append(_item("PLUS-1", "Reserve 20% of capacity for pluses: file the first improvement of the staff itself", "portfolio", "portfolio-manager", "Next", "an issue labeled plus exists"))
    return items


def render_roadmap(m: dict, items: list[dict]) -> str:
    out = [f"# {m['name']} roadmap", "", "Generated by GENESIS-1 from the instance manifest; the backlog is `docs/issues/`. Edit the manifest or the issues, not this file.", ""]
    for ms in ("Now", "Next", "Later"):
        out += [f"## {ms}", ""] + [f"- **{i['id']}** {i['title'].split(': ', 1)[1]} ({i['workstream']})" for i in items if i["milestone"] == ms] + [""]
    return "\n".join(out)


def charter(m: dict) -> str:
    g = "\n".join(f"{i}. {x}" for i, x in enumerate(m["goals"], 1))
    return (f"# {m['name']} charter\n\n{m['positioning']}\n\n## Goals (one project each)\n{g}\n\n## Staff\nSee org/team.json: phase 0 runs now, later phases activate only when their gate probes pass.\n\n"
            f"## Runtime\n{m['runtime']['provider']}; other runtimes are PORT-* backlog items.\n\n## Limits\nBudget {m['budget']['usd_per_month']} USD/month. Identity-bound steps are owner cards (org/OWNER-CARD.md).\n")


def write(m: dict, out, root: Path = REPO) -> dict:
    out = Path(out)
    items = backlog(m, root)
    (out / "docs" / "issues").mkdir(parents=True, exist_ok=True)
    for it in items:
        (out / "docs" / "issues" / f"{it['id']}.json").write_text(json.dumps(it, indent=2) + "\n", encoding="utf-8")
    (out / "ROADMAP.md").write_text(render_roadmap(m, items), encoding="utf-8")
    (out / "org").mkdir(exist_ok=True)
    (out / "org" / "charter.md").write_text(charter(m), encoding="utf-8")
    (out / "doctrine").mkdir(exist_ok=True)
    (out / "doctrine" / "team.json").write_text((root / "doctrine" / "team.json").read_text(encoding="utf-8"), encoding="utf-8")
    (out / "org" / "team.json").write_text(json.dumps(team.recommend(m, root), indent=2) + "\n", encoding="utf-8")
    prov = m["runtime"]["provider"]
    (out / "org" / "infra.json").write_text(json.dumps({"provider": prov, "needs": [{"part": p, "what": w, "status": "pending", "probe": f"{p} reports live in the first tick's evidence"} for p, w in INFRA[prov]]}, indent=2) + "\n", encoding="utf-8")
    return {"items": len(items), "by_milestone": {k: sum(1 for i in items if i["milestone"] == k) for k in ("Now", "Next", "Later")}}
