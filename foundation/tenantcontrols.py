"""TENANT-CONTROLS-1: the hosted, multi-tenant tier stays closed until every control is proven (Q-GAP-multi-tenant-controls). Ultrastable is the foundation for any autonomous system.

  python3 -m foundation tenantcontrols --check    the record is current, every unproven control has a queue item, and the hosted option is still deferred
  python3 -m foundation tenantcontrols --write    run every probe, write docs/security/multi-tenant-controls.json, file Q-MTC-<id> for each unproven control
  python3 -m foundation tenantcontrols --ready    exit 0 only when every control is proven (the gap's own done check)

Controls and their probes are data: doctrine/tenant-controls.json. A control is proven when all its probes pass; nothing is marked proven by hand.
Consumers: checks.yml (--check), docs/issues/Q-GAP-multi-tenant-controls.json (--ready), tests/foundation/test_tenantcontrols.py.
"""
from __future__ import annotations
import json, sys
from pathlib import Path

from . import queue

REPO = Path(__file__).resolve().parents[1]
DEFS, RECORD, PILOT = "doctrine/tenant-controls.json", "docs/security/multi-tenant-controls.json", "doctrine/pilot-model.json"


def evaluate(root=REPO) -> dict:
    root = Path(root)
    d = json.loads((root / DEFS).read_text(encoding="utf-8"))
    out = []
    for c in d["controls"]:
        res = [{"probe": p, "passes": queue.probe(root, p)[0]} for p in c["probes"]]
        proven = all(r["passes"] for r in res)
        out.append({"id": c["id"], "obligation": c["obligation"], "owner": c["owner"], "status": "proven" if proven else "unproven", "probes": res,
                    **({"needs": c["needs"]} if c.get("needs") and not proven else {}), **({"gate": c["gate"]} if c.get("gate") and not proven else {})})
    unproven = [c["id"] for c in out if c["status"] == "unproven"]
    return {"_doc": "Generated by `python3 -m foundation tenantcontrols --write` from doctrine/tenant-controls.json. Do not edit: a status is the result of its probes.",
            "hosted_tier": "ready to offer" if not unproven else "closed", "proven": len(out) - len(unproven), "total": len(out), "unproven": unproven, "controls": out}


def _item(root: Path, c: dict) -> str:
    iid = "Q-MTC-" + c["id"]
    f = root / "docs/issues" / f"{iid}.json"
    if not f.exists():
        failing = next(p["probe"] for p in c["probes"] if not p["passes"])
        body = (f"**Owner:** {c['owner']}\n**Trigger:** every executor run\n**Done check:** {failing}\n**Status:** open\n\n"
                f"Multi-tenant control `{c['id']}` is unproven: {c['obligation']}. Needed: {c.get('needs', 'make the failing probe pass')}. "
                "The hosted tier stays closed until this is proven. Source: doctrine/tenant-controls.json (TENANT-CONTROLS-1).")
        f.write_text(json.dumps({"id": iid, "title": f"{iid}: {c['obligation']}", "body": body, "labels": [f"role:{c['owner']}", "gap"], "milestone": "Next", "workstream": "Gaps"}, indent=2) + "\n", encoding="utf-8")
    return iid


def write(root=REPO) -> dict:
    root, rec = Path(root), evaluate(root)
    (root / RECORD).parent.mkdir(parents=True, exist_ok=True)
    (root / RECORD).write_text(json.dumps(rec, indent=1) + "\n", encoding="utf-8")
    rec["filed"] = [_item(root, c) for c in rec["controls"] if c["status"] == "unproven" and not c.get("gate")]  # a gated control is the owner's: never work for a model
    return rec


def check(root=REPO) -> list[str]:
    root, bad = Path(root), []
    if not (root / RECORD).is_file():
        return [f"{RECORD} missing (run tenantcontrols --write)"]
    now = evaluate(root)
    if json.loads((root / RECORD).read_text(encoding="utf-8")) != now:
        bad.append(f"{RECORD} is stale (run tenantcontrols --write)")
    ol = root / "doctrine/open-loops.json"
    gates = {g["id"] for g in json.loads(ol.read_text(encoding="utf-8"))["gates"]} if ol.is_file() else set()
    for c in now["controls"]:
        if c["status"] != "unproven":
            continue
        if c.get("gate"):
            if c["gate"] not in gates:
                bad.append(f"control {c['id']} is unproven and its gate {c['gate']} is not in doctrine/open-loops.json")
        elif not (root / "docs/issues" / f"Q-MTC-{c['id']}.json").is_file():
            bad.append(f"control {c['id']} is unproven and has no queue item (run tenantcontrols --write)")
    hosted = next(o for o in json.loads((root / PILOT).read_text(encoding="utf-8"))["options"] if o["id"] == "hosted")
    if now["unproven"] and not hosted["status"].startswith("deferred"):
        bad.append(f"the hosted option is offered ({hosted['status']!r}) while controls are unproven: {', '.join(now['unproven'])}")
    return bad


def main(argv) -> int:
    a = argv[0] if argv else "--check"
    if a == "--write":
        r = write(); print(f"{r['proven']}/{r['total']} controls proven; hosted tier {r['hosted_tier']}; filed {r['filed']}"); return 0
    if a == "--ready":
        r = evaluate(); print(f"{r['proven']}/{r['total']} controls proven" + ("" if not r["unproven"] else "; unproven: " + ", ".join(r["unproven"]))); return 0 if not r["unproven"] else 1
    bad = check()
    print("\n".join("tenantcontrols: " + b for b in bad) or "tenantcontrols ok"); return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
