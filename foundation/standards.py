"""Standards as code (STANDARDS-FIRST-1, Rowan 2026-11-25: "Standards, don't reinvent the wheel. Apply standards."). Ultrastable is the foundation
for any autonomous system. `seed/standards/standards.json` is the register (standard, status, support, how, tests, and for every audited row the
decision, the measured adoption, the homegrown equivalent, what conformance would change, its cost and the probes that are run);
`seed/standards/surfaces.json` lists every HTTP surface. `check` fails CI when a declared standard is unsupported, a test
the register names does not exist, the register is stale, the Worker serves a path that is not registered, or a surface
lacks discovery. `apply` regenerates the register table in docs/standards/AGENTIC-STANDARDS.md. Ultra-stable:
infrastructure that works so nobody notices."""
from __future__ import annotations
import datetime as dt, json, re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
REG, SURF, SCHEMA = "seed/standards/standards.json", "seed/standards/surfaces.json", "seed/standards/standards.schema.json"
DOC, SNAP = "docs/standards/AGENTIC-STANDARDS.md", "seed/worker/contract/mcp-tools.v1.json"
ENTRY = "seed/worker/src/index.js"
BEGIN, END = "<!-- standards:begin (generated by `python3 -m foundation standards --apply`) -->", "<!-- standards:end -->"
ICON = {"supported": "supported", "partial": "partial", "planned": "planned", "not_applicable": "n/a"}
DECISION = {"adopt-now": "adopt now", "adopt-later": "adopt later", "decline": "decline"}


def _load(root, rel):
    return json.loads((Path(root) / rel).read_text(encoding="utf-8"))


def _validate(schema, value, path="$"):
    """The register against its schema, by the one JSON Schema validator every config uses (foundation/schemas.py)."""
    from . import schemas
    return schemas.validate(schema, value, path)


def probe(root, spec: str) -> str:
    """One measured reading of a register row. '' when it holds, else why not.
    file:PATH | grep:PATH::REGEX | absent:GLOB (a homegrown or foreign artefact must not exist) | glob:GLOB (at least one match)
    | schemas (python3 -m foundation configschema --check) | commits (python3 -m foundation standards --commits)."""
    root = Path(root)
    kind, _, arg = spec.partition(":")
    if kind == "file":
        return "" if (root / arg).is_file() else f"{arg} is missing"
    if kind == "grep":
        f, _, rx = arg.partition("::")
        p = root / f
        if not p.is_file():
            return f"{f} is missing"
        return "" if re.search(rx, p.read_text(encoding="utf-8")) else f"{f} does not match {rx}"
    if kind == "glob":
        return "" if any(root.glob(arg)) else f"nothing matches {arg}"
    if kind == "absent":
        hit = sorted(p.relative_to(root).as_posix() for p in root.glob(arg))
        return f"{hit[0]} exists" if hit else ""
    if kind == "schemas":
        from . import configschema
        bad = configschema.check(root)
        return f"{len(bad)} schema finding(s), first: {bad[0]}" if bad else ""
    if kind == "commits":
        from . import commitlint
        bad = commitlint.check(root)
        return f"{len(bad)} commit-title finding(s), first: {bad[0]}" if bad else ""
    return f"unknown probe {spec!r}"


def audit(root, reg) -> list[str]:
    """STANDARDS-FIRST-1: every audited row (one with a `decision`) is measured, not declared. The decision, the adoption reading, the homegrown
    equivalent, what conformance would change and its cost are data; the probes are run here; an adopt-later row names a filed item; a declined
    row says why and when to look again; a watched row has a scout source that turns a new version of the standard into an item."""
    root, bad = Path(root), []
    scout = {s.get("standard"): s for s in (_load(root, "doctrine/scout.json").get("sources") or []) if s.get("standard")} if (root / "doctrine/scout.json").is_file() else None
    undecided = [e["id"] for e in reg["entries"] if "decision" not in e]
    if len(undecided) > reg.get("undecided_ceiling", 0):
        bad.append(f"register: {len(undecided)} rows carry no decision, above the ceiling {reg.get('undecided_ceiling', 0)} (the count only shrinks; a new row arrives audited)")
    for e in reg["entries"]:
        if "decision" not in e:
            continue
        i, dec, ad = e["id"], e["decision"], e.get("adoption")
        for k in ("adoption", "conformance", "cost", "probes", "audited"):
            if not e.get(k):
                bad.append(f"{i}: an audited row needs `{k}`")
        for p in e.get("homegrown", []):
            if not any(root.glob(p)):
                bad.append(f"{i}: homegrown path missing: {p}")
        for spec in e.get("probes", []):
            why = probe(root, spec)
            if why:
                bad.append(f"{i}: probe {spec.split(':')[0]} fails: {why}")
        if dec == "adopt-now" and (ad not in ("adopted", "partial") or e["support"] not in ("supported", "partial")):
            bad.append(f"{i}: adopt-now means adopted or partial, with support supported or partial")
        if dec == "adopt-later":
            item = e.get("tracked_by", "")
            if not re.fullmatch(r"Q-[A-Za-z0-9-]+", item) or not (root / "docs/issues" / (item + ".json")).is_file():
                bad.append(f"{i}: adopt-later needs `tracked_by` naming a filed item in docs/issues/")
        if dec == "decline" and not (e.get("reason") and e.get("revisit") and e["support"] == "not_applicable"):
            bad.append(f"{i}: a declined row needs a reason, a `revisit` condition and support not_applicable")
        if ad == "homegrown" and not e.get("homegrown"):
            bad.append(f"{i}: adoption homegrown must name the homegrown paths")
        if e.get("watch") and scout is not None and (scout.get(i) or {}).get("id") != e["watch"]:
            bad.append(f"{i}: watch names scout source {e['watch']!r}, but doctrine/scout.json has no source with that id and \"standard\": \"{i}\"")
    if scout is not None:
        ids = {e["id"] for e in reg["entries"]}
        bad += [f"doctrine/scout.json: source {s['id']} watches standard {k!r}, which is not in the register" for k, s in scout.items() if k not in ids]
    return bad


def live(root=REPO, fetch=None) -> list[str]:
    """`--live`: the rows whose proof is an address. GET only; each `live` entry is {url, contains?, content_type?, json_keys?}."""
    import urllib.request, urllib.error
    def get(url):
        req = urllib.request.Request(url, headers={"user-agent": "ultrastable-audit/1.0", "accept": "*/*"}, method="GET")
        try:
            with urllib.request.urlopen(req, timeout=20) as r:
                return r.status, r.headers.get("content-type", ""), r.read(400000).decode("utf-8", "replace")
        except urllib.error.HTTPError as e:
            return e.code, e.headers.get("content-type", ""), e.read(400000).decode("utf-8", "replace")
    fetch, bad = fetch or get, []
    for e in _load(root, REG)["entries"]:
        for lv in e.get("live", []):
            try:
                status, ctype, body = fetch(lv["url"])
            except Exception as x:  # noqa: BLE001 - an unreachable address is the finding, named with its row
                bad.append(f"{e['id']}: {lv['url']} unreachable: {type(x).__name__}: {str(x)[:120]}"); continue
            if status != lv.get("status", 200):
                bad.append(f"{e['id']}: {lv['url']} answered {status}, expected {lv.get('status', 200)}"); continue
            if lv.get("content_type") and lv["content_type"] not in ctype:
                bad.append(f"{e['id']}: {lv['url']} is {ctype or 'untyped'}, expected {lv['content_type']}")
            for c in lv.get("contains", []):
                if c not in body:
                    bad.append(f"{e['id']}: {lv['url']} does not contain {c!r}")
            if lv.get("json_keys"):
                try:
                    j = json.loads(body)
                    bad += [f"{e['id']}: {lv['url']} lacks {k!r}" for k in lv["json_keys"] if k not in j]
                except ValueError:
                    bad.append(f"{e['id']}: {lv['url']} is not JSON")
    return bad


def adopted(root, sid: str) -> list[str]:
    """The closing probe of a Q-STD-<id> item: the row reads adopted and every probe on it passes."""
    root = Path(root)
    e = next((x for x in _load(root, REG)["entries"] if x["id"] == sid), None)
    if not e:
        return [f"{sid}: no such row in {REG}"]
    bad = [] if e.get("adoption") == "adopted" else [f"{sid}: adoption is {e.get('adoption')!r}, not adopted"]
    return bad + [f"{sid}: probe {p.split(':')[0]} fails: {w}" for p in e.get("probes", []) for w in [probe(root, p)] if w]


def audit_table(root=REPO) -> str:
    """The audit as one table: every audited row with its measured adoption, decision and what it rests on."""
    rows = ["| Standard | Adoption (measured) | Decision | Homegrown equivalent | Item / reason |", "|---|---|---|---|---|"]
    for e in _load(root, REG)["entries"]:
        if "decision" in e:
            rows.append(f"| {e['name']} | {e['adoption']} | {DECISION[e['decision']]} | {', '.join(e.get('homegrown') or []) or 'none'} | {e.get('tracked_by') or (e.get('revisit') and 'revisit: ' + e['revisit']) or ''} |")
    return "\n".join(rows)


def check(root=REPO, today=None) -> list[str]:
    root, bad = Path(root), []
    reg, surf = _load(root, REG), _load(root, SURF)
    bad += _validate(_load(root, SCHEMA), reg)
    if bad:
        return bad
    bad += audit(root, reg)
    ids = {e["id"]: e for e in reg["entries"]}
    if len(ids) != len(reg["entries"]):
        bad.append("register: duplicate standard id")
    today = today or dt.date.today()
    age = (today - dt.date.fromisoformat(reg["checked"])).days
    if age > reg.get("stale_after_days", 120):
        bad.append(f"register: last checked {reg['checked']} ({age} days ago); re-check the sources and bump `checked`")
    for e in reg["entries"]:
        i, sup = e["id"], e["support"]
        if sup in ("supported", "partial"):
            for p in e.get("how", []) or []:
                if not (root / p).exists():
                    bad.append(f"{i}: how path missing: {p}")
            if not e.get("how"):
                bad.append(f"{i}: {sup} needs `how` paths")
            if not e.get("tests"):
                bad.append(f"{i}: {sup} needs at least one test")
            for t in e.get("tests", []):
                f = root / t["file"]
                if not f.exists():
                    bad.append(f"{i}: test file missing: {t['file']}")
                elif t["name"] not in f.read_text(encoding="utf-8"):
                    bad.append(f"{i}: test {t['name']!r} not found in {t['file']}")
        if sup == "partial" and not e.get("gap"):
            bad.append(f"{i}: partial support must state the gap")
        if sup == "planned" and not (e.get("tracked_by") and (e.get("acl") or e.get("decision"))):
            bad.append(f"{i}: planned needs tracked_by and the acl file where it will land (or an audited decision)")
        if sup == "not_applicable" and not e.get("reason"):
            bad.append(f"{i}: not_applicable needs a reason")
        if e["status"] != "stable" and sup in ("supported", "partial") and not e.get("acl"):
            bad.append(f"{i}: status {e['status']} but no anti-corruption layer file named in `acl` (unstable standards must be isolated)")
        if e.get("acl") and not (root / e["acl"]).exists():
            bad.append(f"{i}: acl file missing: {e['acl']}")
    # surfaces
    paths = set()
    for s in surf["surfaces"]:
        paths.add(s["path"])
        if not s.get("description"):
            bad.append(f"surface {s['path']}: no description")
        if not s["discoverable"] and not s.get("reason"):
            bad.append(f"surface {s['path']}: not discoverable and no reason")
        if s["discoverable"] and not s["standards"]:
            bad.append(f"surface {s['path']}: discoverable but names no standard")
        for sid in s["standards"]:
            if sid not in ids:
                bad.append(f"surface {s['path']}: unknown standard {sid}")
            elif ids[sid]["support"] not in ("supported", "partial"):
                bad.append(f"surface {s['path']}: declares {sid}, which is {ids[sid]['support']} in the register")
    served = set(re.findall(r"pathname\s*===\s*['\"]([^'\"]+)['\"]", (root / ENTRY).read_text(encoding="utf-8")))
    for p in sorted(served - paths):
        bad.append(f"{ENTRY} serves {p}, which is not registered in {SURF} (new surface without discovery)")
    snap = _load(root, SNAP)
    if snap["contract_version"].split(".")[0] != surf["contract_version"].split(".")[0]:
        bad.append("contract: snapshot and surfaces.json disagree on the major version")
    doc = root / DOC
    if not doc.exists() or table(reg) not in doc.read_text(encoding="utf-8"):
        bad.append(f"{DOC}: standards table is out of date; run `python3 -m foundation standards --apply`")
    return bad


def table(reg) -> str:
    rows = ["| Standard | Body | Status | Support | Decision | Proof (test) |", "|---|---|---|---|---|---|"]
    for e in reg["entries"]:
        proof = "; ".join(f"`{t['name']}`" for t in e.get("tests", [])) or (e.get("tracked_by") or e.get("reason") or "")
        rows.append(f"| {e['name']} | {e['body']} | {e['status']} | {ICON[e['support']]} | {DECISION.get(e.get('decision'), '')} | {proof} |")
    return "\n".join([BEGIN, "", *rows, "", END])


def apply(root=REPO) -> bool:
    root = Path(root)
    doc, t = root / DOC, table(_load(root, REG))
    s = doc.read_text(encoding="utf-8")
    a, b = s.find(BEGIN), s.find(END)
    new = s[:a] + t + s[b + len(END):] if a != -1 and b != -1 else s.rstrip("\n") + "\n\n" + t + "\n"
    if new == s:
        return False
    doc.write_text(new, encoding="utf-8")
    return True
