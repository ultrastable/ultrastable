"""LIVE-LINKS-1 (Rowan, 2026-11-25): "If somebody sees the code, then show them where it's running, show them the URL ... what I'm not
seeing is where these repos are actually deployed." Ultrastable is the foundation for any autonomous system.

Every repository's README carries a Live block that says where its code is running: the public URL, its health report, its statements, the
Worker it runs as and how it gets there. The block is computed from the registries (doctrine/fleet-contract.json, doctrine/tenant-repos.json,
doctrine/topology.json), never typed by hand, so a moved domain changes every README by code.

  python3 -m foundation livelinks --block ID            print the block for one system (ID as in `fleetcontract --list`), or `fleet` for the table of all
  python3 -m foundation livelinks --write README --id ID   insert or replace the block in a README (after the first heading)
  python3 -m foundation livelinks --check               this repository's README carries the current fleet table (in checks)
  python3 -m foundation livelinks --check --readme PATH --id ID   another repository's README carries its current block
  python3 -m foundation livelinks --live                fetch every system's README from its repository and fail one that does not link its live URL
Tests: tests/foundation/test_livelinks.py."""
from __future__ import annotations
import json, re, sys
from pathlib import Path
from . import fleetcontract as FC

REPO = Path(__file__).resolve().parents[1]
START, END = "<!-- live:start (generated by python3 -m foundation livelinks from the platform's registries; do not edit) -->", "<!-- live:end -->"
BLOCK = re.compile(r"<!-- live:start[^>]*-->.*?<!-- live:end -->\n?", re.S)
PLATFORM = "https://ultrastable.io"


def rows(root=REPO) -> list[dict]:
    """One row per live system: id, origin, repository, how it runs."""
    pol = json.loads((Path(root) / FC.POLICY).read_text(encoding="utf-8"))
    ten = json.loads((Path(root) / "doctrine/tenant-repos.json").read_text(encoding="utf-8")).get("tenants", {})
    out = []
    for s in FC.systems(root):
        t = ten.get(s["id"], {})
        runs = pol.get("runs_as", {}).get(s["id"]) or (f"Cloudflare Worker `{t['worker']}`, deployed from this repository's `main` by the Ultrastable platform" if t.get("worker") else None)
        out.append({"id": s["id"], "origin": s["origin"], "repo": t.get("repo") or pol.get("repos", {}).get(s["id"]), "runs_as": runs})
    return out


def block(sid: str, root=REPO) -> str:
    rs = rows(root)
    if sid == "fleet":
        body = ["## Where everything runs", "", "| System | Live | Repository |", "|---|---|---|"]
        body += [f"| {r['id']} | [{r['origin']}]({r['origin']}/) | [{r['repo']}](https://github.com/{r['repo']}) |" for r in rs if r["origin"] and r["repo"]]
        body += ["", f"The same list, read live: [{PLATFORM}/directory]({PLATFORM}/directory). Each system's health is at `/health` and what it states, with the endpoint behind each statement, at `/claims.json`."]
        return "\n".join([START, *body, END]) + "\n"
    r = next((x for x in rs if x["id"] == sid), None)
    if not r or not r["origin"]:
        return "\n".join([START, "## Live", "", "Not deployed yet. This repository holds the system's manifest; when its first version is deployed, this block names where it runs.",
                          "", f"Runs on [Ultrastable]({PLATFORM}/), the foundation for any autonomous system.", END]) + "\n"
    o = r["origin"]
    body = ["## Live", "", f"**Running at [{o}]({o}/)**", "", "| | |", "|---|---|",
            f"| Health report | [{o}/health]({o}/health) |",
            f"| What it states, and the endpoint behind each statement | [{o}/claims.json]({o}/claims.json) |"]
    if r["runs_as"]:
        body.append(f"| Runs as | {r['runs_as']} |")
    if sid != "ultrastable":
        body.append(f"| Platform | [Ultrastable]({PLATFORM}/), the foundation for any autonomous system · [every system running on it]({PLATFORM}/directory) |")
    else:
        body.append(f"| Every system running on it | [{PLATFORM}/directory]({PLATFORM}/directory) |")
    return "\n".join([START, *body, END]) + "\n"


def place(text: str, blk: str) -> str:
    """Replace the block, or insert it after the first markdown heading (or at the top when there is none)."""
    if BLOCK.search(text):
        return BLOCK.sub(lambda _m: blk, text, count=1)
    m = re.search(r"^# .*\n", text, re.M)
    return (text[:m.end()] + "\n" + blk + text[m.end():]) if m else blk + "\n" + text


def has(text: str, blk: str) -> bool:
    m = BLOCK.search(text)
    return bool(m) and m.group(0).strip() == blk.strip()


def check(root=REPO) -> list[str]:
    root, bad = Path(root), []
    core = (root / "README.md").read_text(encoding="utf-8")
    for sid in ("ultrastable", "fleet"):
        b = block(sid, root)
        if b.strip() not in core:
            bad.append(f"README.md: the Live block for `{sid}` is missing or stale; run python3 -m foundation livelinks --write README.md --id {sid}")
    for r in rows(root):
        if not r["repo"]:
            bad.append(f"{r['id']}: live at {r['origin']} and no repository named (doctrine/tenant-repos.json or `repos` in {FC.POLICY})")
    for rel in FC.RULE_FILES:
        if "LIVE-LINKS-1" not in (root / rel).read_text(encoding="utf-8"):
            bad.append(f"{rel}: rule LIVE-LINKS-1 missing")
    return bad


def live(root=REPO, fetch=FC._fetch) -> list[dict]:
    """Each system's README, read from its repository's main, links the address the system runs at."""
    out = []
    for r in rows(root):
        if not (r["repo"] and r["origin"]):
            out.append({"id": r["id"], "ok": False, "why": "no repository or no origin"})
            continue
        st, _, body = fetch(f"https://raw.githubusercontent.com/{r['repo']}/main/README.md", "ultrastable-livelinks/1")
        ok = st == 200 and r["origin"] in body
        out.append({"id": r["id"], "ok": ok, "why": "" if ok else (f"README unreadable ({st}): a private or missing repository reads unmeasured, not passed" if st != 200 else f"README does not link {r['origin']}")})
    return out


def _multi(text: str, ids: list[str], root=REPO) -> str:
    for sid in ids:  # a README may carry several blocks (the core: its own, then the fleet table); each is matched by its first heading line
        b = block(sid, root)
        head = b.split("\n")[1]
        pat = re.compile(r"<!-- live:start[^>]*-->\n" + re.escape(head) + r".*?<!-- live:end -->\n?", re.S)
        text = pat.sub(lambda _m: b, text, count=1) if pat.search(text) else place_after(text, b)
    return text


def place_after(text: str, blk: str) -> str:
    last = None
    for last in BLOCK.finditer(text):
        pass
    if last:
        return text[:last.end()] + "\n" + blk + text[last.end():]
    return place(text, blk)


def main(argv=None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    arg = lambda f, d=None: argv[argv.index(f) + 1] if f in argv else d  # noqa: E731
    if "--block" in argv:
        print(block(arg("--block")), end="")
        return 0
    if "--write" in argv:
        p = Path(arg("--write"))
        ids = arg("--id", "").split(",")
        new = _multi(p.read_text(encoding="utf-8"), ids)
        if new != p.read_text(encoding="utf-8"):
            p.write_text(new, encoding="utf-8")
            print(f"wrote the Live block ({', '.join(ids)}) to {p}")
        return 0
    if "--live" in argv:
        res = live()
        for r in res:
            print(("ok   " if r["ok"] else "FAIL ") + r["id"] + (": " + r["why"] if r["why"] else ""))
        return 0 if all(r["ok"] for r in res) else 1
    if "--readme" in argv:
        sid, text = arg("--id"), Path(arg("--readme")).read_text(encoding="utf-8")
        ok = block(sid).strip() in text
        print(f"{sid}: " + ("README carries its current Live block" if ok else f"README lacks its current Live block; run livelinks --write {arg('--readme')} --id {sid}"))
        return 0 if ok else 1
    bad = check()
    for b in bad:
        print("FAIL " + b)
    print("livelinks ok: the README names where the platform and every system run" if not bad else f"livelinks: {len(bad)} problems")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
