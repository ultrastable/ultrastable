"""Needs-you page: the one place that lists what a person must do. Ultrastable is the foundation for any autonomous system.

  python3 -m foundation needsyou [--check]
  python3 -m foundation needsyou --settle     GATE-SETTLE-1: remove every item whose `resolved_when` evidence is in (watchdog.yml runs it daily)

Renders NEEDS-YOU.md from foundation/data/needs-you.json. Each item is two lines and one link. --check fails when the file is
stale or an item lacks an https link, so a card, a file path or a menu cannot come back.
"""
from __future__ import annotations
import json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = Path(__file__).parent / "data" / "needs-you.json"
OUT = ROOT / "NEEDS-YOU.md"


def render(root=ROOT) -> str:
    d = json.loads(DATA.read_text(encoding="utf-8"))
    lines = ["# Needs you", "",
             "Everything else is done by the system. These are the only acts that need your identity, each with the one click that does it and what already happens if you never click.", ""]
    deps = json.loads((ROOT / "doctrine/unattended.json").read_text(encoding="utf-8"))["dependencies"]  # UNATTENDED-365: measured state decides what is still asked
    by = {}
    for x in deps:
        if x.get("needs_you"):
            by.setdefault(x["needs_you"], []).append(x)
    done = {k: v for k, v in by.items() if all(x["status"] == "closed" for x in v)}
    for i in d["items"]:
        if i["id"] in done:
            continue
        lines += [f"## {i['title']}", f"{i['why']} If you do nothing: {i['default']}", f"**[{i['button']}]({i['url']})**", ""]
    lines += ["## Already done for you", ""] + [f"- {x}" for x in d["done_for_you"]] + [f"- {i['title']}: done ({'; '.join(x['evidence'] for x in done[i['id']])})." for i in d["items"] if i["id"] in done] + ["", "_Generated by `python3 -m foundation needsyou` from `foundation/data/needs-you.json`. Index of everything else: [INDEX.md](INDEX.md)._", ""]
    return "\n".join(lines)


def check(root=ROOT) -> list[str]:
    d = json.loads(DATA.read_text(encoding="utf-8"))
    bad = [f"{i['id']}: needs one https link" for i in d["items"] if not re.fullmatch(r"https://\S+", i.get("url", ""))]
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != render(root):
        bad.append("NEEDS-YOU.md is stale: run python3 -m foundation needsyou")
    return bad


def _http_says(url: str, text: str, fetch=None) -> bool:
    """GET url; True only on HTTP 200 whose body contains text. A network or HTTP error is not evidence (the gate stays open)."""
    if fetch is not None:
        return fetch(url, text)
    import urllib.request, urllib.error
    try:
        req = urllib.request.Request(url, headers={"user-agent": "ultrastable-needsyou-settle"})
        with urllib.request.urlopen(req, timeout=15) as r:
            return r.status == 200 and text in r.read(400_000).decode("utf-8", "replace")
    except (urllib.error.URLError, OSError, ValueError) as e:
        print(f"needsyou: {url} unreadable ({e.__class__.__name__}); gate stays open")
        return False


def resolved(item: dict, env, fetch=None) -> bool:
    """GATE-SETTLE-1: an owner gate states the evidence that closes it. `actions-running`: this code is running in a GitHub Actions job (so Actions
    is not refused); `env:A|B`: one of the named credentials is bound; `http:URL ~ TEXT` (GATE-SETTLE-2): the live page at URL answers 200 and says
    TEXT, which is how a credential the Worker sealed itself (connect flow) is seen. `resolved_when` may be a list: any one piece of evidence settles.
    An item without `resolved_when` is closed only by a change to the data."""
    ws = item.get("resolved_when", "")
    for w in ([ws] if isinstance(ws, str) else list(ws)):
        if w == "actions-running" and env.get("GITHUB_ACTIONS") == "true":
            return True
        if w.startswith("env:") and any(env.get(n) for n in w[4:].split("|")):
            return True
        if w.startswith("http:") and "~" in w:
            url, text = (s.strip() for s in w[5:].split("~", 1))
            if url.startswith("https://") and text and _http_says(url, text, fetch):
                return True
    return False


def settle(root=ROOT, env=None, data=None, fetch=None) -> list[str]:
    """Remove every owner gate whose evidence is in; the page, the done list and the deep-link baseline follow. Returns the ids removed."""
    import os, datetime
    env = os.environ if env is None else env
    data = Path(data) if data else DATA
    d = json.loads(data.read_text(encoding="utf-8"))
    gone = [i["id"] for i in d["items"] if resolved(i, env, fetch)]
    if gone:
        day = datetime.datetime.now(datetime.timezone.utc).date().isoformat()
        d.setdefault("done_for_you", []).extend(f"{i.get('title', i['id'])}: settled {day} on its own evidence ({i['resolved_when'] if isinstance(i['resolved_when'], str) else ' or '.join(i['resolved_when'])})."
                                                for i in d["items"] if i["id"] in gone)
        d["items"] = [i for i in d["items"] if i["id"] not in gone]
        data.write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        pc = Path(root) / "doctrine/point-and-click.json"
        if pc.exists():
            t = pc.read_text(encoding="utf-8"); j = json.loads(t)
            for v in j.values():
                if isinstance(v, dict) and "deep_link_baseline" in v:
                    v["deep_link_baseline"] = [x for x in v["deep_link_baseline"] if x not in gone]
            pc.write_text(json.dumps(j, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return gone


def main(argv=None) -> int:
    import sys
    argv = sys.argv[1:] if argv is None else argv
    if "--settle" in argv:
        gone = settle()
        if gone:
            OUT.write_text(render(), encoding="utf-8")
            if "--changed-file" in argv:
                Path(argv[argv.index("--changed-file") + 1]).write_text("1", encoding="utf-8")
        print("settled: " + (", ".join(gone) or "none"))
        return 0
    if "--check" in argv:
        bad = check()
        print("\n".join(bad) or "needs-you ok")
        return 1 if bad else 0
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT.name}")
    return 0
