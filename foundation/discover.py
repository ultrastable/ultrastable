"""DISCOVER-1 (Rowan, 2026-11-25): every Ultrastable system is public and discoverable. Ultrastable is the foundation for any autonomous system.

  python3 -m foundation discover --gen     write site/directory-data.js (the platform plus every live tenant) from the registries
  python3 -m foundation discover --check   fail when a live tenant worker has no live showcase with a home, when the generated list is
                                           stale, when the homepage or /directory stops rendering it, or when the seed stops serving the
                                           manifest, footer and heartbeat
  python3 -m foundation discover --live    fetch https://ultrastable.io/directory.json and the homepage; fail when a core system is missing

Inputs: doctrine/tenant-repos.json, doctrine/topology.json, doctrine/stakeholders.json. Consumers: site/directory.js (homepage block,
/directory, /directory.json, the external register and recheck), seed/worker/src/discover.js. Tests: tests/foundation/test_discover.py."""
from __future__ import annotations
import json, sys, urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = "site/directory-data.js"
LICENSE = "LicenseRef-Ultrastable-USL-1.0"
PLATFORM = {"id": "ultrastable", "name": "Ultrastable", "url": "https://ultrastable.io/", "repo": "https://github.com/ultrastable/ultrastable",
            "license": LICENSE, "kind": "platform", "summary": "The platform every system here runs on. It runs on itself."}


def _j(root, rel):
    return json.loads((Path(root) / rel).read_text(encoding="utf-8"))


def live_tenants(root=REPO) -> dict:
    """Tenants whose code is registered and, when they name a worker, whose worker is live in the topology."""
    root = Path(root)
    tr = _j(root, "doctrine/tenant-repos.json").get("tenants", {})
    live = {w["id"] for w in _j(root, "doctrine/topology.json").get("workers", []) if w.get("state") == "live"}
    return {k: v for k, v in tr.items() if v.get("state") not in ("planned", "retired") and (not v.get("worker") or v["worker"] in live)}


def core(root=REPO) -> list:
    root = Path(root)
    shows = {c["id"]: c for c in _j(root, "doctrine/stakeholders.json").get("showcases", [])}
    tr = _j(root, "doctrine/tenant-repos.json").get("tenants", {})
    out = [dict(PLATFORM)]
    for sid, c in shows.items():
        if c.get("status") != "live" or not c.get("home"):
            continue
        repo = (tr.get(sid) or {}).get("repo")
        out.append({"id": sid, "name": c["name"], "url": c["home"], "repo": "https://github.com/" + repo if repo else None,
                    "license": LICENSE, "kind": "tenant", "summary": c.get("summary", "")[:240]})
    return out


def render(root=REPO) -> str:
    return ("// SPDX-License-Identifier: " + LICENSE + "\n// generated by python3 -m foundation discover --gen (DISCOVER-1); do not edit\nexport default "
            + json.dumps(core(root), indent=1, ensure_ascii=False) + ";\n")


def check(root=REPO) -> list[str]:
    root, bad = Path(root), []
    shows = {c["id"]: c for c in _j(root, "doctrine/stakeholders.json").get("showcases", [])}
    for sid in live_tenants(root):
        c = shows.get(sid)
        if not c or c.get("status") != "live" or not c.get("home"):
            bad.append(f"{sid}: live tenant with no live showcase and home in doctrine/stakeholders.json, so the homepage cannot list it")
    p = root / OUT
    if not p.exists() or p.read_text(encoding="utf-8") != render(root):
        bad.append(f"{OUT} is stale: run python3 -m foundation discover --gen")
    w = (root / "site/worker.js").read_text(encoding="utf-8")
    for needle, why in [("directoryBlock(", "homepage does not render the directory"), ('case "/directory"', "/directory is not served"),
                        ('case "/directory.json"', "/directory.json is not served"), ("/api/directory/register", "external systems cannot register"),
                        ("recheckDirectory(", "the site tick does not recheck listings")]:
        if needle not in w:
            bad.append(f"site/worker.js: {why}")
    for rel, needles in [("seed/worker/src/index.js", ["discoverRoute(", "directoryHeartbeat("]), ("seed/worker/src/ui.js", ["Built on <a"])]:
        t = (root / rel).read_text(encoding="utf-8") if (root / rel).exists() else ""
        for n in needles:
            if n not in t:
                bad.append(f"{rel}: missing {n} (DISCOVER-1)")
    return bad


def live(base="https://ultrastable.io") -> list[str]:
    bad = []
    def get(path):
        req = urllib.request.Request(base + path, headers={"user-agent": "ultrastable-discover-probe/1"})
        with urllib.request.urlopen(req, timeout=20) as r:
            return r.read().decode("utf-8", "replace")
    try:
        d = json.loads(get("/directory.json"))
        home = get("/")
    except Exception as e:  # reported, never swallowed
        return [f"directory unreachable: {e}"]
    for c in core():
        if c["id"] not in {x["id"] for x in d.get("core", [])}:
            bad.append(f"{c['id']}: missing from /directory.json")
        if c["kind"] == "tenant" and c["url"] not in home:
            bad.append(f"{c['id']}: homepage does not link {c['url']}")
    return bad


def main(argv=None) -> int:
    a = argv if argv is not None else sys.argv[1:]
    if "--gen" in a:
        (REPO / OUT).write_text(render(), encoding="utf-8")
        print("wrote", OUT, len(core()), "systems")
        return 0
    bad = live() if "--live" in a else check()
    for b in bad:
        print("DISCOVER-1:", b)
    print("discover:", "ok" if not bad else f"{len(bad)} problem(s)")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
