"""PROMOTE-1: strategy and promotion as a closed loop. Ultrastable is the foundation for any autonomous system.

  python3 -m foundation promote --check                 facts prove themselves, kits are fresh, every channel has route/signal/consumer
  python3 -m foundation promote --kits                  render application kits (outreach/applications/<profile>/) from forms + facts
  python3 -m foundation promote --plan [--apply]        score channels; --apply writes ops/promotion/plan.json and Q-PROMO items
  python3 -m foundation promote --outcome CH --kind K   record an outcome (accepted|replied|listed|rejected|silent); re-weights CH

Strategy is computed, not written: a channel's fit is its `requires` evaluated against outreach/facts.json, so a programme that
needs an open-source licence drops out until the fact changes, and re-enters by itself when it does. Kits contain only claims from
the fact bank; numbers in answers come only from facts, and a fact whose probe fails blocks the kit.
"""
from __future__ import annotations
import argparse, datetime as dt, json, re, sys, urllib.request
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
DOC = "doctrine/promotion.json"
FACTS = "outreach/facts.json"
PROFILES = "outreach/profiles.json"
KIT_DIR = "outreach/applications/ultrastable"
KIND_DELTA = {"accepted": 0.5, "listed": 0.3, "replied": 0.2, "rejected": -0.1, "silent": -0.2}


def _j(root, p):
    return json.loads((Path(root) / p).read_text(encoding="utf-8"))


def probe(root, spec: str, live=False):
    """Return the probe's value (bool or int), or None when it cannot run here (http without --live)."""
    kind, _, arg = spec.partition(":")
    root = Path(root)
    if kind == "file":
        return (root / arg).exists()
    if kind in ("grep", "nogrep"):
        path, _, rx = arg.partition("::")
        p = root / path
        hit = p.is_file() and re.search(rx, p.read_text(encoding="utf-8", errors="replace")) is not None
        return hit if kind == "grep" else not hit
    if kind == "jsonlen":
        path, _, key = arg.partition("::")
        d = json.loads((root / path).read_text(encoding="utf-8"))
        for k in key.split("."):
            d = d[k]
        return len(d)
    if kind == "http":
        if not live:
            return None
        try:
            with urllib.request.urlopen(urllib.request.Request(arg, headers={"user-agent": "ultrastable-promote"}), timeout=15) as r:
                return 200 <= r.status < 400
        except Exception as e:  # recorded by the caller as a failed probe
            return False
    raise ValueError(f"unknown probe kind {kind!r}")


def eval_facts(root=REPO, live=False) -> dict:
    out = {}
    for fid, f in _j(root, FACTS)["facts"].items():
        v = probe(root, f["probe"])
        if "op" in f:
            ok = isinstance(v, int) and not isinstance(v, bool) and v >= f["value"]
        else:
            ok = v is True
        if ok and live and f.get("live_probe"):
            ok = probe(root, f["live_probe"], live=True) is not False
        out[fid] = {"true": bool(ok), "measured": v, **f}
    return out


def render_fact(f: dict) -> str:
    return f"at least {f['value']} {f['claim']}" if "op" in f else f["claim"]


def guard(text: str, root=REPO) -> list[str]:
    """Blocked patterns from the outreach profile, plus: no digits outside fact substitutions, no links."""
    pats = _j(root, PROFILES)["profiles"]["ultrastable"]["blocked_patterns"]
    errs = [f"blocked pattern {p!r}" for p in pats if re.search(p, text, re.I)]
    if re.search(r"\d", text):
        errs.append("digit outside a fact")
    if re.search(r"https?://", text):
        errs.append("link in answer")
    return errs


def build_kit(form: dict, facts: dict, root=REPO) -> tuple[str, list[str]]:
    errs, lines = [], [f"# {form['programme']}: application kit", "",
                        f"Apply at: {form['url']}  ",
                        f"Cycle: {form['cycle']}  ",
                        f"Question source: {form['source_status']}. {form.get('source_note', '')}".rstrip(), "",
                        "Generated by `python3 -m foundation promote --kits` from outreach/forms and outreach/facts.json; every claim below is a fact whose probe passed.", ""]
    for r in form.get("requires", []):
        if not facts.get(r, {}).get("true"):
            errs.append(f"{form['id']}: requirement {r} is false: not a fit now")
    for i, q in enumerate(form["questions"], 1):
        raw = re.sub(r"\{fact:[a-z_]+\}", "", q["a"])
        for e in guard(raw, root):
            errs.append(f"{form['id']} Q{i}: {e}")
        def sub(m):
            f = facts.get(m.group(1))
            if not f or not f["true"]:
                errs.append(f"{form['id']} Q{i}: fact {m.group(1)} is not proven")
                return "[unproven]"
            if m.group(1) not in q["facts"]:
                errs.append(f"{form['id']} Q{i}: fact {m.group(1)} used but not declared")
            return render_fact(f)
        text = re.sub(r"\{fact:([a-z_]+)\}", sub, q["a"])
        text = text[0].upper() + text[1:]
        text = re.sub(r"\. ([a-z])", lambda m: ". " + m.group(1).upper(), text)
        if len(text) > q["limit"]:
            errs.append(f"{form['id']} Q{i}: {len(text)} chars over limit {q['limit']}")
        lines += [f"## {i}. {q['q']}", f"_({q['status']}, {len(text)}/{q['limit']} characters)_", "", text, ""]
    lines += ["## Filled at submission (identity-bound)", ""] + [f"- {o}" for o in form.get("owner_fields", [])] + [""]
    return "\n".join(lines), errs


def forms(root=REPO) -> list[dict]:
    d = _j(root, DOC)
    return [_j(root, c["form"]) for c in d["channels"] if c.get("form")]


def kits(root=REPO, write=True) -> tuple[dict, list[str]]:
    facts, out, errs = eval_facts(root), {}, []
    for f in forms(root):
        text, e = build_kit(f, facts, root)
        fit = not any("not a fit now" in x for x in e)
        errs += [x for x in e if "not a fit now" not in x]
        path = f"{KIT_DIR}/{f['id']}.md"
        out[path] = text if fit else None
    index = ["# Application kits", "", "Generated by `python3 -m foundation promote --kits`. Ordered by channel score; not-a-fit programmes list the fact that keeps them out.", ""]
    for row in plan(root)["channels"]:
        if row["kind"] != "application":
            continue
        kit = f"{KIT_DIR}/{row['id']}.md"
        state = f"[kit]({row['id']}.md)" if out.get(kit) else ("not a fit now" if row["blocked_by"] else "per-programme links in outreach/STATUS.md")
        index.append(f"- **{row['id']}** score {row['score']}: {state}" + (f" (blocked by fact: {', '.join(row['blocked_by'])})" if row["blocked_by"] else ""))
    out[f"{KIT_DIR}/README.md"] = "\n".join(index) + "\n"
    if write:
        for p, t in out.items():
            fp = Path(root) / p
            if t is None:
                if fp.exists():
                    fp.unlink()
                continue
            fp.parent.mkdir(parents=True, exist_ok=True)
            fp.write_text(t, encoding="utf-8")
    return out, errs


def weights(root=REPO) -> dict:
    p = Path(root) / _j(root, DOC)["weights_file"]
    return json.loads(p.read_text(encoding="utf-8")).get("weights", {}) if p.is_file() else {}


def plan(root=REPO) -> dict:
    d, facts, w = _j(root, DOC), eval_facts(root), weights(root)
    rows = []
    for c in d["channels"]:
        blocked = [r for r in c.get("requires", []) if not facts.get(r, {}).get("true")]
        fit = 0.0 if blocked else 1.0
        score = round(c["reach"] * fit * w.get(c["id"], 1.0) / c["cost"], 2)
        if blocked:
            state = "not-a-fit-now"
        elif c["needs"] == "none":
            state = "system-runs"
        else:
            state = "kit-ready-identity-gate"
        rows.append({"id": c["id"], "kind": c["kind"], "score": score, "state": state, "blocked_by": blocked, "gate": c.get("gate"),
                     "signal": c["signal"], "route": c.get("route") or c.get("form")})
    rows.sort(key=lambda r: (-r["score"], r["id"]))
    return {"generated_by": "python3 -m foundation promote --plan", "channels": rows}


def items(p: dict) -> list[dict]:
    """Executor items for channels the system runs itself (credential-free)."""
    out = []
    for r in p["channels"]:
        if r["state"] != "system-runs":
            continue
        out.append({"id": f"Q-PROMO-{r['id']}", "title": f"Q-PROMO-{r['id']}: keep the {r['id']} promotion channel live",
                    "body": f"**Owner:** marketing-manager\n**Trigger:** every promote --plan pass\n**Done check:** grep:ops/promotion/outcomes.jsonl::\"channel\": \"{r['id']}\"\n"
                            f"**Prediction:** promotion_outcomes_recorded >= 1 within 336 h\n**Status:** open\n\nRoute: {r['route']}. Signal back: {r['signal']}. "
                            f"Record the result with `python3 -m foundation promote --outcome {r['id']} --kind listed|silent`; the outcome re-weights the channel.",
                    "labels": ["role:marketing-manager", "growth", "promotion"], "milestone": "Next", "workstream": "Growth"})
    return out


def check(root=REPO) -> list[str]:
    d, errs = _j(root, DOC), []
    facts = eval_facts(root)
    for c in d["channels"]:
        for k in ("id", "kind", "needs", "signal", "consumer", "reach", "cost"):
            if k not in c:
                errs.append(f"channel {c.get('id')}: missing {k}")
        if c.get("needs") == "owner-identity" and c.get("gate") not in d["gates_allowed"]:
            errs.append(f"channel {c['id']}: owner-identity without an allowed gate (only identity-bound acts may wait on the owner)")
        if c.get("needs") == "none" and not c.get("route"):
            errs.append(f"channel {c['id']}: system channel without a route")
        if c.get("consumer") and not (Path(root) / c["consumer"]).exists():
            errs.append(f"channel {c['id']}: consumer {c['consumer']} does not exist")
        for r in c.get("requires", []):
            if r not in facts:
                errs.append(f"channel {c['id']}: requires unknown fact {r}")
    out, kerrs = kits(root, write=False)
    errs += kerrs
    for p, t in out.items():
        fp = Path(root) / p
        if t is None and fp.exists():
            errs.append(f"{p}: stale kit for a not-a-fit programme; run promote --kits")
        elif t is not None and (not fp.is_file() or fp.read_text(encoding="utf-8") != t):
            errs.append(f"{p}: kit out of date; run promote --kits")
    return errs


def outcome(root, channel, kind, note=""):
    d = _j(root, DOC)
    if channel not in {c["id"] for c in d["channels"]}:
        raise SystemExit(f"unknown channel {channel}")
    if kind not in KIND_DELTA:
        raise SystemExit(f"kind must be one of {sorted(KIND_DELTA)}")
    with open(Path(root) / d["outcomes_file"], "a", encoding="utf-8") as f:
        f.write(json.dumps({"at": dt.date.today().isoformat(), "channel": channel, "kind": kind, "note": note}) + "\n")
    wp = Path(root) / d["weights_file"]
    wd = json.loads(wp.read_text(encoding="utf-8"))
    wd.setdefault("weights", {})[channel] = round(min(3.0, max(0.1, wd["weights"].get(channel, 1.0) + KIND_DELTA[kind])), 2)
    wp.write_text(json.dumps(wd, indent=1) + "\n", encoding="utf-8")
    return wd["weights"][channel]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="promote")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--kits", action="store_true")
    ap.add_argument("--plan", action="store_true")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--outcome")
    ap.add_argument("--kind")
    ap.add_argument("--note", default="")
    ap.add_argument("--root", default=str(REPO))
    a = ap.parse_args(argv)
    root = Path(a.root)
    if a.outcome:
        print(f"{a.outcome} weight now {outcome(root, a.outcome, a.kind, a.note)}")
        return 0
    if a.kits:
        _, errs = kits(root)
        for e in errs:
            print("kit:", e, file=sys.stderr)
        return 1 if errs else 0
    if a.plan:
        p = plan(root)
        for r in p["channels"]:
            print(f"{r['score']:>5}  {r['id']:<14} {r['state']}" + (f"  blocked_by={','.join(r['blocked_by'])}" if r["blocked_by"] else "") + (f"  gate={r['gate']}" if r["state"] == "kit-ready-identity-gate" else ""))
        if a.apply:
            (root / _j(root, DOC)["plan_file"]).write_text(json.dumps(p, indent=1) + "\n", encoding="utf-8")
            for it in items(p):
                (root / "docs/issues" / f"{it['id']}.json").write_text(json.dumps(it, indent=2) + "\n", encoding="utf-8")
        return 0
    errs = check(root)
    for e in errs:
        print("promote:", e, file=sys.stderr)
    print("promote ok" if not errs else f"promote: {len(errs)} problem(s)")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
