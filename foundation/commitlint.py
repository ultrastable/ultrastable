"""STANDARDS-FIRST-1: the titles of the commits the system writes itself follow the Conventional Commits 1.0.0 header grammar,
`<type>[(scope)][!]: <description>`. Ultrastable is the foundation for any autonomous system.

The titles are generated by code (a workflow step, a script, scripts/land_data.py), so the lint reads the generators, before any commit exists:
every `git commit -m "..."` and every `land_data.py "..."` under the globs in doctrine/commit-convention.json. A title that does not parse is on the
shrink-only baseline or the check fails. The type is the loop that wrote the commit (watchdog, queue, lane ...), which the spec allows beside feat
and fix; nothing here derives a version number from a title.

  python3 -m foundation standards --commits
Tests: tests/foundation/test_commitlint.py."""
from __future__ import annotations
import json, re
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
PATH = "doctrine/commit-convention.json"
HEADER = re.compile(r"^(?P<type>[a-z][a-z0-9-]*)(\((?P<scope>[^()\r\n]+)\))?(?P<breaking>!)?: (?P<description>\S.*)$")
SITE = re.compile(r"""(?:git\s+commit\b[^\n|;&]*?-m\s+|land_data\.py\s+)(["'])(?P<title>.+?)\1""")


def parse(title: str):
    """The header's parts, or None when the title is not a Conventional Commits header."""
    m = HEADER.match(title.split("\n", 1)[0])
    return m.groupdict() if m else None


def titles(root=REPO, cfg=None) -> list[tuple[str, str]]:
    """(file, title) for every commit title a generator under the configured globs writes."""
    root = Path(root)
    cfg = cfg or json.loads((root / PATH).read_text(encoding="utf-8"))
    out = []
    for g in cfg["generators"]:
        for p in sorted(root.glob(g)):
            if p.is_file():
                rel = p.relative_to(root).as_posix()
                out += [(rel, m.group("title")) for m in SITE.finditer(p.read_text(encoding="utf-8")) if not m.group("title").startswith(("<", "$"))]  # a usage line or a title held in a variable
    return out


def check(root=REPO) -> list[str]:
    root = Path(root)
    cfg = json.loads((root / PATH).read_text(encoding="utf-8"))
    base, bad, seen = cfg["baseline"], [], set()
    if len(base) > cfg["baseline_ceiling"]:
        bad.append(f"{PATH}: baseline holds {len(base)} titles, above its ceiling {cfg['baseline_ceiling']} (it only shrinks: fix the generator)")
    found = titles(root, cfg)
    if not found:
        bad.append(f"{PATH}: no commit title found under the generator globs; the lint is reading nothing")
    for f, t in found:
        key = f"{f}: {t}"
        seen.add(key)
        if not parse(t) and key not in base:
            bad.append(f"{f}: commit title {t!r} is not `<type>[(scope)]: <description>` (Conventional Commits 1.0.0)")
    for key in base:
        if key not in seen:
            bad.append(f"{PATH}: baseline names {key!r}, which no generator writes any more; remove it")
        elif parse(key.split(": ", 1)[1]):
            bad.append(f"{PATH}: {key!r} conforms now; remove it from the baseline")
    return bad
