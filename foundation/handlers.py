"""Autonomous routes for owner-only steps. Each handler returns (ok, detail, completes_hint) and may write files under `out`.
Ultrastable is the foundation for any autonomous system, so a handler does everything short of the identity-bound act.
Network goes through `ctx.http(method, url, body)` (injected; tests use fixtures). A 401/403 answer is a refusal: recorded, not circumvented.
"""
from __future__ import annotations
import json
from pathlib import Path

from . import filing


def _write(out: Path, name: str, data) -> str:
    p = Path(out) / name
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    return name


def filing_plan(m, ctx, out, apply):
    pl = filing.plan(m, portal_ok=ctx.facts.get("national_patent_portal_ok", True))
    _write(out, "org/filing-plan.json", pl)
    ctx.state["filing_card"] = pl["card"]
    return True, f"filing plan written ({pl['status']}, {len(pl['routes'])} route(s))"


def portal_probe(m, ctx, out, apply):
    url = ctx.facts.get("patent_portal_status_url")
    if not url or ctx.http is None:
        return False, "no status URL or no network surface; recorded, daily probe scheduled by the plan"
    code, _ = ctx.http("GET", url, None)
    ctx.facts["national_patent_portal_ok"] = code < 400
    return code < 400, f"portal status page answered {code}"


def entity_deferral(m, ctx, out, apply):
    rows = [{"route": r, "eligible_as_individual": not r.get("entity_only", False)} for r in m["funding"]["routes"]]
    _write(out, "org/funding-eligibility.json", rows)
    return True, f"{sum(1 for r in rows if not r['eligible_as_individual'])} entity-only route(s) deferred, rest run as individual"


def brand_checklist(m, ctx, out, apply):
    items = ["org avatar", "repo social preview", "pinned repos", "domain verification", "org 2FA requirement"]
    _write(out, "org/brand-ui-checklist.json", {"items": items, "assets_from": "brand/", "name": m["brand"]["public_name"]})
    return True, f"{len(items)} UI-only items prepared with assets"


def no_account_channels(m, ctx, out, apply):
    ch = ["repository README and releases", "open-source registry pull requests", "static feed (RSS/Atom) on the site"]
    _write(out, "org/social-queue.json", {"mode": m["social"]["mode"], "no_account_channels": ch, "queued_posts": "generated by social_generate, dry-run"})
    return True, "work moves through channels that need no account; posts queued dry-run"


def funding_packets(m, ctx, out, apply):
    _write(out, "org/funding-plan.json", {"routes": m["funding"]["routes"], "mode": "packets drafted, guarded, unsent"})
    return True, f"{len(m['funding']['routes'])} route(s) planned"


def outreach_dry_run(m, ctx, out, apply):
    _write(out, "org/outreach-plan.json", {"mode": "dry-run", "sender": "none until OUT-SENDER passes", "never": "the owner's personal mailbox"})
    return True, "outreach queued dry-run"


def email_alias(m, ctx, out, apply):
    zone, acct, dest = ctx.env.get("CLOUDFLARE_ZONE_ID"), ctx.env.get("CLOUDFLARE_ACCOUNT_ID"), ctx.env.get(m["owner"]["contact_binding"])
    if not (zone and acct and dest and ctx.http):
        return False, "needs CLOUDFLARE_ZONE_ID, CLOUDFLARE_ACCOUNT_ID, the contact binding and a network surface"
    domain = m.get("domain", "")
    plan = [("POST", f"/accounts/{acct}/email/routing/addresses", {"email": "<contact binding>"}),
            ("POST", f"/zones/{zone}/email/routing/rules", {"matchers": [{"type": "literal", "field": "to", "value": f"hello@{domain}"}], "actions": [{"type": "forward", "value": ["<contact binding>"]}], "name": "hello alias"})]
    if not apply:
        return True, "dry run: alias plan recorded (" + ", ".join(p[1] for p in plan) + ")"
    for method, path, body in plan:
        body = json.loads(json.dumps(body).replace("<contact binding>", dest))
        code, _ = ctx.http(method, "https://api.cloudflare.com/client/v4" + path, body)
        if code in (401, 403):
            return False, f"refused ({code}) at {path}; recorded, not re-routed"
        if code >= 400 and code != 409:
            return False, f"failed ({code}) at {path}"
    return True, "alias rule created; destination verification mail goes to the existing contact"


REGISTRY = {f.__name__: f for f in (filing_plan, portal_probe, entity_deferral, brand_checklist, no_account_channels, funding_packets, outreach_dry_run, email_alias)}
