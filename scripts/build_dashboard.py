#!/usr/bin/env python3
"""DASHBOARD-1: the public dashboard preview shows the real control plane, computed from this repository, never typed in.

  python3 scripts/build_dashboard.py          regenerate site/dashboard-data.js
  python3 scripts/build_dashboard.py --check  fail if it is stale or a panel has no source file

Ultrastable watching itself is the demo: no customer data is shown or held. Each panel names the file it was computed from. The live tick feed
(ticks, dispatches, breaches as they happen) is tracked by Q-LOOP-live-clock; until a deployed runtime reports, the panel says so.
Consumers: site/worker.js (/dashboard), tests/foundation/test_dashboard.py, the checks workflow, doctrine/pilot-model.json (pilot options panel)."""
import json, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = "site/dashboard-data.js"
HEADER = "// generated by scripts/build_dashboard.py from the repository; do not edit\n"


def j(root, rel):
    return json.loads((Path(root) / rel).read_text(encoding="utf-8"))


def build(root=ROOT) -> dict:
    root = Path(root)
    from foundation import pins
    loops = j(root, "instances/ultrastable/loop-registry.json")["loops"]
    by_area = {}
    for l in loops:
        by_area[l.get("area", "other")] = by_area.get(l.get("area", "other"), 0) + 1
    obj = j(root, "instances/ultrastable/objectives.json")
    reg = j(root, "doctrine/registers.json")
    det = j(root, "doctrine/detectors.json")
    pj = j(root, "site/pins.json")["pins"]
    pstat = {}
    for p in pj:
        pstat[p["status"]] = pstat.get(p["status"], 0) + 1
    unprobed = pins.unprobed(root)
    issues = list((root / "docs/issues").glob("*.json"))
    trust = j(root, "instances/ultrastable/trust-ledger.json")
    rows = trust.get("rows", [])
    rungs = {}
    for r in rows:
        k = r.get("rung", "?")
        rungs[k] = rungs.get(k, 0) + 1
    try:
        sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=root, capture_output=True, text=True).stdout.strip()
        asof_at = subprocess.run(["git", "log", "-1", "--format=%cI"], cwd=root, capture_output=True, text=True).stdout.strip()
    except OSError:
        sha, asof_at = "", ""
    cl = [json.loads(x) for x in (root / "ops/criticality.jsonl").read_text(encoding="utf-8").splitlines() if x.strip()] if (root / "ops/criticality.jsonl").is_file() else []
    last = cl[-1] if cl else None
    crit_head = f"k = {last['k']} ({last['gate']})" if last else "no tick recorded yet"
    crit_rows = [[c, "met" if ok else "not met"] for c, ok in last["clauses"].items()] if last else []
    live = j(root, "instances/ultrastable/live-runtime.json")
    tenant0 = {
        "level": 0, "panels": [
            {"id": "loops", "title": "Closed loops", "source": "instances/ultrastable/loop-registry.json",
             "headline": f"{len(loops)} registered loops", "rows": [[k, v] for k, v in sorted(by_area.items())],
             "note": "Each has a trigger, owner, SLA, two independent paths and a closing probe."},
            {"id": "metrics", "title": "Objectives and metrics", "source": "instances/ultrastable/objectives.json",
             "headline": f"{len(obj['objectives'])} objectives, {len(obj['metrics'])} metrics",
             "rows": [[m["name"], f"{m['kind']} / {m['source']}"] for m in obj["metrics"]],
             "note": "Same rows bootstrap seeds for any system. A declared metric with no probe is a breach by design."},
            {"id": "failures", "title": "Failure modes under audit", "source": "doctrine/detectors.json",
             "headline": f"{len(reg['failure_modes'])} failure modes, {len(det['detectors'])} live detectors",
             "rows": [[d["id"], d["failure_mode"]] for d in det["detectors"]],
             "note": "A failing detector files one issue; the same failure twice means change the approach, three times an incident."},
            {"id": "pins", "title": "Capabilities", "source": "site/pins.json",
             "headline": " / ".join(f"{v} {k}" for k, v in sorted(pstat.items())),
             "rows": [[p["name"], p["status"]] for p in pj],
             "note": "Status is checked against code and probes on every build."},
            {"id": "roadmap", "title": "Roadmap", "source": "docs/issues",
             "headline": f"{len(issues)} issue files, {len(unprobed)} without a runnable probe (shrink-only)",
             "rows": [["open issues without a probe", len(unprobed)], ["issue files", len(issues)]],
             "note": "Every open item carries an owner, a trigger and a done check the system runs."},
            {"id": "criticality", "title": "Criticality", "source": "ops/criticality.jsonl",
             "headline": crit_head, "rows": crit_rows,
             "note": "Ship. Verify. Spend less than it earns. Feed the next loop. k = verified deploys / (cost + human touches); below 1 the queue is limited to deploys and cost."},
            {"id": "trust", "title": "Earned autonomy", "source": "instances/ultrastable/trust-ledger.json",
             "headline": f"{len(rows)} trust rows", "rows": [[k, v] for k, v in sorted(rungs.items())],
             "note": "Autonomy widens per surface and action from graded predictions, never by itself."},
        ],
        "live_feed": {"available": bool(live["runtimes"]), "tracked_by": "Q-LOOP-live-clock",
                      "runtimes": [{"tenant": r["tenant"], "level": r["level"], "health": r["health"], "parent": r.get("parent", "")} for r in live["runtimes"]],
                      "says": "Read from the deployed runtimes' own /health when this page loads: the last tick each reports, and whether the child reports to its parent."},
    }
    # TENANT-1: one view that takes a tenant id; tenant 0 is Ultrastable on itself. Only registered tenants render; others are 404.
    return {"asof": sha, "asof_at": asof_at, "pilot": j(root, "doctrine/pilot-model.json"), "pilot_offer": j(root, "doctrine/pilot-offer.json"), "tenants": {"ultrastable": tenant0}}


def render(d) -> str:
    return HEADER + "export default " + json.dumps(d, indent=1, ensure_ascii=False) + ";\n"


def check(root=ROOT) -> list:
    root = Path(root)
    bad = []
    d = build(root)
    for t in d["tenants"].values():
        for p in t["panels"]:
            if not (root / p["source"]).exists():
                bad.append(f"panel {p['id']}: source {p['source']} missing")
    for p in []:
        if not (root / p["source"]).exists():
            bad.append(f"panel {p['id']}: source {p['source']} missing")
    cur = root / OUT
    if not cur.is_file():
        bad.append(f"{OUT} missing; run python3 scripts/build_dashboard.py")
    else:
        old = cur.read_text(encoding="utf-8").replace("\r\n", "\n")
        new = render(d)
        strip = lambda t: "\n".join(l for l in t.splitlines() if '"asof"' not in l and '"asof_at"' not in l)  # the commit id moves on every commit; the data may not
        if strip(old) != strip(new):
            bad.append(f"{OUT} is stale; run python3 scripts/build_dashboard.py")
    return bad


if __name__ == "__main__":
    if "--check" in sys.argv:
        b = check()
        print("dashboard ok" if not b else "\n".join(b))
        sys.exit(1 if b else 0)
    (ROOT / OUT).write_text(render(build()), encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
