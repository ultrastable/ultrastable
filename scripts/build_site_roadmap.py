#!/usr/bin/env python3
"""SITE-PINS-1: every status pin and honest gap on the public site must be tied to a real docs/issues item and to code that exists.

  python3 scripts/build_site_roadmap.py          regenerate site/roadmap-data.js from site/pins.json + docs/issues
  python3 scripts/build_site_roadmap.py --check  fail (exit 1) on a dangling pin, a wrong status, or a stale generated file

Rules: a pin has an issue that exists with owner, trigger, done check and status; its code paths exist; a live pin's done check passes and its
issue is done; a testing or pinned pin's issue is open and its done check does not pass yet (when it passes the pin must be promoted).
Consumers: site/worker.js (/engineers, /how, /roadmap, /roadmap.json), tests/foundation/test_site_roadmap.py, the checks workflow."""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from foundation.boundary import probe_ok  # noqa: E402

OUT = "site/roadmap-data.js"


def field(body, name):
    m = re.search(r"\*\*" + name + r":\*\*\s*([^\n]+)", body)
    return m.group(1).strip() if m else ""


def load(root=ROOT):
    root = Path(root)
    src = json.loads((root / "site/pins.json").read_text(encoding="utf-8"))
    issues, bad = {}, []

    def issue(iid, ctx):
        if iid in issues:
            return issues[iid]
        f = root / "docs/issues" / f"{iid}.json"
        if not f.is_file():
            bad.append(f"{ctx}: issue {iid} does not exist in docs/issues")
            return None
        d = json.loads(f.read_text(encoding="utf-8"))
        r = {"id": iid, "title": d["title"].split(": ", 1)[-1], "owner": field(d["body"], "Owner"), "trigger": field(d["body"], "Trigger"),
             "done": field(d["body"], "Done check"), "status": field(d["body"], "Status"), "milestone": d.get("milestone", "")}
        # SHELVED-NOT-DONE-1 (2026-11-21): DISPOSE-1 closes an item that timed out as `shelved`; that is a disposition, not a fix, so a pin or
        # gap backed by it stays as it is unless its done check passes (main went red when 6-hour shelving made two open gaps read as done).
        # A shelved item whose done check passes was fixed after all and counts as done.
        if (field(d["body"], "Disposition") or "").lower().startswith("shelved") and not probe_ok(root, r["done"]):
            r["status"] = "shelved"
        for k in ("owner", "trigger", "done", "status"):
            if not r[k]:
                bad.append(f"{ctx}: issue {iid} lacks {k}")
        issues[iid] = r
        return r

    for p in src["pins"]:
        ctx = f"pin '{p['name']}'"
        i = issue(p["issue"], ctx)
        for c in p["code"]:
            if not (root / c).is_file():
                bad.append(f"{ctx}: code path {c} does not exist")
        if not p["code"]:
            bad.append(f"{ctx}: no code path")
        if not i or not i["done"]:
            continue
        passes = probe_ok(root, i["done"])
        isdone = i["status"].lower().startswith(("done", "closed"))
        if p["status"] == "live" and not (passes and isdone):
            bad.append(f"{ctx}: marked live but issue {i['id']} is {'not done' if not isdone else 'done check fails: ' + i['done']}")
        if p["status"] in ("testing", "pinned") and (isdone or passes):
            bad.append(f"{ctx}: marked {p['status']} but {i['id']} is done or its done check passes; promote the pin")
        if p["status"] not in ("live", "testing", "pinned"):
            bad.append(f"{ctx}: unknown status {p['status']}")
    for text, iid in src["gaps"]:
        i = issue(iid, "gap '" + text[:40] + "'")
        if i and i["status"].lower().startswith(("done", "closed")):
            bad.append(f"gap '{text[:40]}': issue {iid} is done; remove the gap")
    data = {"pins": src["pins"], "gaps": [{"text": t, "issue": i} for t, i in src["gaps"]], "issues": issues}
    js = ("// GENERATED by scripts/build_site_roadmap.py from site/pins.json and docs/issues/*.json. Do not edit; `--check` fails when stale.\n"
          "export default " + json.dumps(data, indent=1, sort_keys=True) + ";\n")
    return js, bad


def main(argv):
    js, bad = load()
    out = ROOT / OUT
    if "--check" in argv:
        if not out.is_file() or out.read_text(encoding="utf-8") != js:
            bad.append(f"{OUT} is stale; run python3 scripts/build_site_roadmap.py")
        for b in bad:
            print("FAIL", b)
        print("site pins:", "ok" if not bad else f"{len(bad)} problem(s)")
        return 1 if bad else 0
    out.write_text(js, encoding="utf-8")
    for b in bad:
        print("FAIL", b)
    print("wrote", OUT)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
