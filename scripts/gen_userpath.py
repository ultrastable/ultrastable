#!/usr/bin/env python3
"""USER-PATH-1: generate site/userpath.js from doctrine/user-path.json and lint it for people who know nothing about computers.

usage: gen_userpath.py [--check]   (--check exits 1 when site/userpath.js is stale or the data breaks a rule)
Rules: every step has a question and a reason; every action is one https link; text shown to people never uses technical words.
"""
import json, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC, OUT = ROOT / "doctrine/user-path.json", ROOT / "site/userpath.js"
BANNED = re.compile(r"\b(token|terminal|command|cli|api|key|secret|config|repo|repository|oauth|ssh|npm|pip|install|credential|permission|authenticat\w*)\b", re.I)


def problems(d):
    bad = []
    all_steps = list(d["steps"]) + [s for k, v in d.get("tasks", {}).items() if not k.startswith("_") for s in v["steps"]]
    for s in all_steps:
        for k in ("id", "service", "ask", "why"):
            if not s.get(k):
                bad.append(f"{s.get('id', '?')}: missing {k}")
        texts = [s.get("ask", ""), s.get("why", ""), s.get("confirm", "")]
        for a in ("yes", "no"):
            act = s.get(a) or {}
            texts += [act.get("label", ""), act.get("then", "")]
            if act.get("url") and not act["url"].startswith("https://"):
                bad.append(f"{s['id']}: {a} link is not https")
        for t in texts:
            m = BANNED.search(re.sub(r"\[[^\]]*\]", "", t))  # [text] quotes a button label exactly as the other service shows it
            if m:
                bad.append(f"{s['id']}: technical word '{m.group(0)}' in: {t}")
        if not s.get("input") and not s.get("yes"):
            bad.append(f"{s['id']}: no yes action and no input")
    return bad


def render(d):
    return "// generated by scripts/gen_userpath.py from doctrine/user-path.json; do not edit\nexport default " + json.dumps(d, indent=1, ensure_ascii=False) + ";\n"


def main():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    bad = problems(d)
    for b in bad:
        print("userpath:", b)
    text = render(d)
    if "--check" in sys.argv:
        stale = not OUT.exists() or OUT.read_text(encoding="utf-8").replace("\r\n", "\n") != text
        if stale:
            print("userpath: site/userpath.js is stale, run scripts/gen_userpath.py")
        sys.exit(1 if bad or stale else 0)
    if bad:
        sys.exit(1)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
