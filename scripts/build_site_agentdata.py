#!/usr/bin/env python3
"""AGENT-HARNESS-1: generate site/agentdata.js (standards register + blind-spot register) so the site worker can serve them to any agent over MCP.

  python3 scripts/build_site_agentdata.py          regenerate
  python3 scripts/build_site_agentdata.py --check  exit 1 when the generated file is stale"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "site/agentdata.js"


def build(root=ROOT):
    std = json.loads((root / "seed/standards/standards.json").read_text(encoding="utf-8"))
    bs = json.loads((root / "doctrine/blindspots.json").read_text(encoding="utf-8"))
    learned = root / "ops/blindspots/learned.json"
    needs = bs["needs"] + (json.loads(learned.read_text(encoding="utf-8")).get("learned", []) if learned.is_file() else [])
    data = {
        "standards": {"checked": std["checked"], "entries": [{k: e.get(k) for k in ("id", "name", "body", "status", "support", "tracked_by")} for e in std["entries"]]},
        "blind_spots": [{k: n.get(k) for k in ("id", "domain", "why", "class")} for n in needs],
    }
    return "// GENERATED by scripts/build_site_agentdata.py from seed/standards/standards.json and doctrine/blindspots.json. Do not edit; `--check` fails when stale.\nexport default " + json.dumps(data, indent=1, ensure_ascii=False) + ";\n"


if __name__ == "__main__":
    js = build()
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8").replace("\r\n", "\n") if OUT.is_file() else ""
        if cur != js:
            print(f"{OUT.name} is stale; run python3 scripts/build_site_agentdata.py"); sys.exit(1)
        print("agentdata ok")
    else:
        OUT.write_text(js, encoding="utf-8", newline="\n"); print("wrote", OUT)
