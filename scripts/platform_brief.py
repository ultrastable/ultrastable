#!/usr/bin/env python3
"""PLATFORM-BRIEF-1: render deploy/brief/platform-brief.json into a prompt for a cloud platform's own AI agent.

usage: platform_brief.py [platform]   print the brief (cloudflare|gcp|aws|azure; default all)
       platform_brief.py --write      write site/platformbrief.js and docs/PLATFORM-BRIEF.md
       platform_brief.py --check      exit 1 when either file is stale or the data breaks a rule
Rules: every requirement has a need and a probe; every platform maps every requirement; every loop is a chain with ->.
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "deploy/brief/platform-brief.json"
JS, MD = ROOT / "site/platformbrief.js", ROOT / "docs/PLATFORM-BRIEF.md"


def problems(d):
    bad, ids = [], [r["id"] for r in d["requirements"]]
    for r in d["requirements"]:
        for k in ("id", "need", "probe"):
            if not r.get(k):
                bad.append(f"requirement {r.get('id', '?')}: missing {k}")
    for p in d["platforms"]:
        for i in ids:
            if i not in p["maps"]:
                bad.append(f"platform {p['id']}: no mapping for {i}")
        if not p.get("agent_entry"):
            bad.append(f"platform {p['id']}: no agent entry point")
    for l in d["loops"]:
        if "->" not in l:
            bad.append(f"loop is not a chain: {l}")
    return bad


def render(d, platform=None):
    ps = [p for p in d["platforms"] if platform in (None, p["id"])]
    out = ["# Ultrastable deployment brief", "", d["intro"], "", "## Requirements (what must exist, and how to prove it)", ""]
    out += [f"- **{r['id']}**: {r['need']} Probe: {r['probe']}." for r in d["requirements"]]
    out += ["", "## Loops that must close", ""] + [f"- {l}" for l in d["loops"]]
    for p in ps:
        out += ["", f"## Target: {p['name']} ({p['running']})", "", f"Ask {p['agent_entry']}. Suggested mapping, which you may improve on:", ""]
        out += [f"- {k}: {v}" for k, v in p["maps"].items()]
    out += ["", "## Your task", "", d["ask"], ""]
    return "\n".join(out)


def main():
    d = json.loads(SRC.read_text(encoding="utf-8"))
    bad = problems(d)
    for b in bad:
        print("brief:", b)
    full = render(d)
    js = "// generated by scripts/platform_brief.py from deploy/brief/platform-brief.json; do not edit\nexport default " + json.dumps({"all": full, **{p["id"]: render(d, p["id"]) for p in d["platforms"]}}, indent=1, ensure_ascii=False) + ";\n"
    a = sys.argv[1:]
    if "--check" in a:
        stale = [f for f, t in ((JS, js), (MD, full)) if not f.exists() or f.read_text(encoding="utf-8").replace("\r\n", "\n") != t]
        for f in stale:
            print(f"brief: {f.relative_to(ROOT)} is stale, run scripts/platform_brief.py --write")
        sys.exit(1 if bad or stale else 0)
    if bad:
        sys.exit(1)
    if "--write" in a:
        JS.write_text(js, encoding="utf-8", newline="\n")
        MD.write_text(full, encoding="utf-8", newline="\n")
        print("wrote", JS.relative_to(ROOT), MD.relative_to(ROOT))
        return
    print(render(d, a[0] if a else None))


if __name__ == "__main__":
    main()
