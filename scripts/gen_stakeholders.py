"""Generate site/stakeholders.js from doctrine/stakeholders.json (STAKEHOLDERS-1). Use --check to fail when stale."""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = json.load(open(root / "doctrine/stakeholders.json"))
out = "// SPDX-License-Identifier: LicenseRef-Ultrastable-USL-1.0\n// generated by scripts/gen_stakeholders.py from doctrine/stakeholders.json; do not edit\nexport default " + json.dumps(src, indent=1, ensure_ascii=False) + ";\n"
dst = root / "site/stakeholders.js"
if "--check" in sys.argv:
    sys.exit(0 if dst.exists() and dst.read_text() == out else 1)
dst.write_text(out)
