// US-SPEC-13 in the composed organisation: the objective F, the monthly autonomy card and the step-budget sweep must run on a real
// tick, not only in module tests. The first two tests build the organisation with createOrg: the composition root hands its report-card
// writer (l3) to the build-out ports (core/org/index.js buildoutPortsFor). The third proves the same assertions through buildoutSteps with l3 supplied.
import test from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { makeDb } from '../_shared/testdb.js';
import { OUT_DIR } from '../../tools/build_migrations.mjs';
import { createOrg } from '../org/index.js';
import { buildoutSteps } from '../org/buildout.js';
import { createConsoleL3 } from '../console-l3/index.js';
import { runTick } from '../src/tick.js';

// The built bundle (OUT_DIR) is regenerated by the integrator after a module gains a migration; the module's own directory is applied too, so this
// test does not depend on that regeneration (every migration is idempotent).
const SLA_MIG = fileURLToPath(new URL('./migrations/', import.meta.url));
const T0 = Date.UTC(2026, 10, 15, 12, 0, 0);
const H = 3600e3;
const stamp = ms => new Date(ms).toISOString().replace('T', ' ').slice(0, 19);
const config = { org_slug: 'wired', claim_ttl_minutes: 120, max_wip_per_role: 3, plus_share: 0.2, policy: { trust: { rungs: ['observed', 'assisted', 'delegated', 'autonomous', 'self-directed', 'self-modifying', 'self-extending'] }, ladder: {}, surfaces: {} } };
const one = (db, sql, ...a) => db.raw.prepare(sql).get(...a);
const noFetch = async () => { throw new Error('no network in this test'); };

async function wired() {
  const db = makeDb([OUT_DIR, SLA_MIG]); const clock = { t: T0 };
  const org = createOrg({ db, env: {}, config, fetch: noFetch, now: () => clock.t });
  db.raw.exec(`INSERT INTO sla_processes (process, done_check, steps, updated_at) VALUES ('change','merged','[{"step":"review","budget_hours":4,"paths":["a","b"]}]','${stamp(T0)}');
    INSERT INTO sla_step_runs (process, step, ref, budget_hours, started_at) VALUES ('change','review','ITEM-1',4,'${stamp(T0 - 9 * H)}')`);
  return { db, org, clock };
}

test('US-13-R11 and US-13-T04 and US-13-R19 in the wired org: a step 9 h into a 4 h budget files one item and one question', async () => {
  const { db, org, clock } = await wired();
  clock.t += 60e3; await org.tick();
  assert.equal(one(db, `SELECT COUNT(*) AS n FROM items WHERE id='STEPBUDGET-CHANGE-REVIEW'`).n, 1);
  assert.equal(one(db, `SELECT COUNT(*) AS n FROM gate_cards WHERE id LIKE 'stepq-change-review%'`).n, 1);
});

test('US-13-T07 and US-13-R19: the wired org computes the autonomy card and the stored objective on its first tick', async () => {
  const { db, org, clock } = await wired();
  clock.t += 60e3; await org.tick();
  assert.ok(one(db, `SELECT name FROM sla_register WHERE name='autonomy_card'`), 'a dated register row for the card');
  const scores = db.raw.prepare(`SELECT dimension, evidence, confidence, status FROM l3_scores WHERE name='autonomy'`).all();
  assert.equal(scores.length, 10);
  for (const s of scores) assert.ok(s.evidence && s.confidence && s.status);
  const f = db.raw.prepare(`SELECT calibrated, terms FROM sla_objective`).all();
  assert.equal(f.length, 1); assert.equal(f[0].calibrated, 0);
  const terms = JSON.parse(f[0].terms);
  assert.deepEqual(Object.keys(terms).filter(k => !terms[k].measured).sort(), ['cost_overrun', 'drift_count', 'integration_gap']);
});

test('US-13-T07 and US-13-R19: through buildoutSteps with l3 supplied: the card, F and the step-budget sweep run on a tick (the behaviour the wiring must reach)', async () => {
  const db = makeDb([OUT_DIR, SLA_MIG]); const clock = { t: T0 };
  const l3 = createConsoleL3({ db, now: () => clock.t });
  db.raw.exec(`INSERT INTO sla_processes (process, done_check, steps, updated_at) VALUES ('change','merged','[{"step":"review","budget_hours":4,"paths":["a","b"]}]','${stamp(T0)}');
    INSERT INTO sla_step_runs (process, step, ref, budget_hours, started_at) VALUES ('change','review','ITEM-1',4,'${stamp(T0 - 9 * H)}')`);
  const extraSteps = buildoutSteps({ db, config, now: () => clock.t, fetch: noFetch, ports: { l3 } }).filter(s => s.name === 'sla');
  clock.t += 60e3;
  const r = await runTick(db, { config, env: {}, now: clock.t, extraSteps });
  assert.equal(r.completed, r.total);
  assert.ok(one(db, `SELECT name FROM sla_register WHERE name='autonomy_card'`));
  assert.equal(db.raw.prepare(`SELECT COUNT(*) AS n FROM l3_scores WHERE name='autonomy'`).get().n, 10);
  assert.equal(db.raw.prepare(`SELECT COUNT(*) AS n FROM sla_objective`).get().n, 1);
  assert.equal(one(db, `SELECT COUNT(*) AS n FROM items WHERE id='STEPBUDGET-CHANGE-REVIEW'`).n, 1);
  assert.equal(one(db, `SELECT COUNT(*) AS n FROM gate_cards WHERE id LIKE 'stepq-change-review%'`).n, 1);
});
