#!/usr/bin/env python3
"""Regenerate docs/ISSUES-BY-AREA.md and the live block of docs/ip/IP-REGISTER.md from this repo's GitHub issues.
Runs hourly and on every issue change (.github/workflows/index.yml). Standard library only.
Env: GITHUB_TOKEN, GITHUB_REPOSITORY (owner/name)."""
import json, os, re, sys, urllib.request, datetime

REPO = os.environ.get("GITHUB_REPOSITORY", "ultrastable/ultrastable")
TOKEN = os.environ.get("GITHUB_TOKEN", "")
AREAS = [  # prefix -> section title (order = order on the page)
    ("P", "Product extraction (P0-P4)"), ("IP", "IP and patent"), ("PF", "Disclosure gate"), ("BIZ", "Business and entity"),
    ("FN", "Funding"), ("PR", "Positioning and pricing"), ("PL", "Platform"), ("WEB", "Site and domains"),
    ("GH", "GitHub setup"), ("QA", "Review"), ("", "Go-to-market and other")]

def issues():
    out, page = [], 1
    while True:
        req = urllib.request.Request(f"https://api.github.com/repos/{REPO}/issues?state=all&per_page=100&page={page}",
                                     headers={"Accept": "application/vnd.github+json", **({"Authorization": f"Bearer {TOKEN}"} if TOKEN else {})})
        batch = json.load(urllib.request.urlopen(req, timeout=30))
        out += [i for i in batch if "pull_request" not in i]
        if len(batch) < 100: return out
        page += 1

def area(title):
    m = re.match(r"([A-Z]+)-?\d*[: ]", title)
    key = m.group(1) if m else ""
    keys = [a for a, _ in AREAS]
    return key if key in keys else ""

def row(i):
    mark = "done" if i["state"] == "closed" else "open"
    who = ", ".join(a["login"] for a in i.get("assignees") or []) or "fleet"
    return f"| [#{i['number']}]({i['html_url']}) | {i['title'].replace('|', '/')} | {mark} | {who} |"

def main():
    all_i = sorted(issues(), key=lambda i: i["number"])
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    open_n = sum(1 for i in all_i if i["state"] == "open")
    lines = ["# Issues by area (live)", "", f"Generated by `tools/build_index.py` from this repo's issues at {now}. Do not edit by hand: change an issue and this page follows within the hour.", "",
             f"{open_n} open, {len(all_i) - open_n} done, {len(all_i)} total. Now/Next/Later view: `ROADMAP.md` and the milestones. Long-form plan with owners, triggers and done checks: `local-workspace/ultrastable-repos/docs/roadmap.md`.", ""]
    for key, title in AREAS:
        rows = [i for i in all_i if area(i["title"]) == key]
        if not rows: continue
        lines += [f"## {title}", "", "| Issue | Title | State | Owner |", "|---|---|---|---|"] + [row(i) for i in rows] + [""]
    open("docs/ISSUES-BY-AREA.md", "w").write("\n".join(lines))
    ip = [i for i in all_i if area(i["title"]) in ("IP", "PF") or "trademark" in i["title"].lower() or i["title"].startswith("P0")]
    block = "\n".join(["<!-- IP-LIVE:start -->", f"Issue status at {now}:", "", "| Issue | Title | State |", "|---|---|---|"] +
                      [f"| [#{i['number']}]({i['html_url']}) | {i['title'].replace('|', '/')} | {'done' if i['state']=='closed' else 'open'} |" for i in ip] + ["<!-- IP-LIVE:end -->"])
    s = open("docs/ip/IP-REGISTER.md").read()
    if "<!-- IP-LIVE:start -->" not in s: s += "\n## Live IP issue status\n<!-- IP-LIVE:start -->\n<!-- IP-LIVE:end -->\n"
    s = re.sub(r"<!-- IP-LIVE:start -->.*?<!-- IP-LIVE:end -->", lambda _: block, s, flags=re.S)
    open("docs/ip/IP-REGISTER.md", "w").write(s)
    print(f"docs/ISSUES-BY-AREA.md: {len(all_i)} issues; IP register: {len(ip)} IP issues")

if __name__ == "__main__":
    main()
