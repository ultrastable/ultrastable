"""SYSTEM-MANIFEST-1 (Rowan, 2026-11-25): "There must be a standard easy way to do this ... standards that can apply these things broadly and
can synchronize across multiple surfaces and providers." Ultrastable is the foundation for any autonomous system.

One manifest per system (`ultrastable.json` at the repository root, its `identity` object validated by standards/system.schema.json) and one
reconciler: every surface that says what the system is and where it runs is rendered from the manifest, never typed per surface.

  python3 scripts/surfaces.py --check  [--root DIR]         the manifest is valid and every surface equals what the manifest renders (exit 1 on drift)
  python3 scripts/surfaces.py --render [--root DIR]         write every surface: README blocks (identity, Live, How this system runs), publiccode.yml,
                                                            catalog-info.yaml (Backstage), CITATION.cff fields, .ultrastable/github.json
  python3 scripts/surfaces.py --plan [github|wellknown|publiccode|all] [--root DIR]   print the provider payloads; nothing is called
  python3 scripts/surfaces.py --validate [--root DIR]       the manifest against the schema only

Pure standard library; carried by every system. Platform wrapper: `python3 -m foundation surfaces`. Tests: tests/test_surfaces.py."""
from __future__ import annotations
import json, re, sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
MANIFEST = "ultrastable.json"
PLATFORM = "https://ultrastable.io"
GITHUB_PLAN = ".ultrastable/github.json"
LIVE_START, LIVE_END = "<!-- live:start (generated by python3 -m foundation livelinks from the platform's registries; do not edit) -->", "<!-- live:end -->"
LIVE_RE = re.compile(r"<!-- live:start[^>]*-->.*?<!-- live:end -->\n?", re.S)
IGNITION = ["unseeded", "seeded", "ticking", "looping", "closing", "instrumented", "critical", "self-sustaining"]  # worker/src/ignition.js STAGES
LIFECYCLE = ["seeded", "planned", "built", "deployed", "live", "autonomous"]  # scripts/seedlife.py STAGES
MERGE = {"has_wiki": False, "allow_squash_merge": True, "allow_merge_commit": False, "allow_rebase_merge": False, "allow_auto_merge": True,
         "allow_update_branch": True, "delete_branch_on_merge": True}


# --- a JSON Schema validator for the subset the manifest schema uses (no third-party package) ---
def validate(value, schema, path="$") -> list[str]:
    errs = []
    t = schema.get("type")
    if t:
        names = {"object": dict, "array": list, "string": str, "boolean": bool, "null": type(None), "number": (int, float), "integer": int}
        ok = any(isinstance(value, names[x]) and not (x in ("number", "integer") and isinstance(value, bool)) for x in ([t] if isinstance(t, str) else t))
        if not ok:
            return [f"{path}: must be {t}"]
    if "enum" in schema and value not in schema["enum"]:
        errs.append(f"{path}: must be one of {', '.join(map(str, schema['enum']))}")
    if isinstance(value, str):
        if len(value) < schema.get("minLength", 0):
            errs.append(f"{path}: shorter than {schema['minLength']} characters")
        if len(value) > schema.get("maxLength", 10 ** 9):
            errs.append(f"{path}: longer than {schema['maxLength']} characters ({len(value)})")
        if "pattern" in schema and not re.search(schema["pattern"], value):
            errs.append(f"{path}: does not match {schema['pattern']}")
    if isinstance(value, list):
        if len(value) > schema.get("maxItems", 10 ** 9):
            errs.append(f"{path}: more than {schema['maxItems']} items")
        if schema.get("uniqueItems") and len({json.dumps(x, sort_keys=True) for x in value}) != len(value):
            errs.append(f"{path}: items repeat")
        for i, x in enumerate(value):
            errs += validate(x, schema.get("items", {}), f"{path}[{i}]")
    if isinstance(value, dict):
        for k in schema.get("required", []):
            if k not in value:
                errs.append(f"{path}.{k}: required")
        props = schema.get("properties", {})
        for k, v in value.items():
            if k in props:
                errs += validate(v, props[k], f"{path}.{k}")
            elif schema.get("additionalProperties") is False:
                errs.append(f"{path}.{k}: not a manifest field" + (" (the stage is computed from evidence, never typed)" if k == "stage" else ""))
    return errs


def schema(root=HERE) -> dict:
    for p in (Path(root) / "standards/system.schema.json", Path(root) / "seed/standards/system.schema.json", HERE / "standards/system.schema.json"):
        if p.is_file():
            return json.loads(p.read_text(encoding="utf-8"))
    raise FileNotFoundError("standards/system.schema.json")


def load(root=HERE) -> dict:
    return json.loads((Path(root) / MANIFEST).read_text(encoding="utf-8"))


def identity(root=HERE) -> dict:
    return load(root).get("identity") or {}


def check_manifest(root=HERE) -> list[str]:
    p = Path(root) / MANIFEST
    if not p.is_file():
        return [f"{MANIFEST}: missing; every repository carries one manifest with an identity object"]
    m = load(root)
    errs = [f"{MANIFEST} {e}" for e in validate(m, schema(root))]
    i, org = m.get("identity") or {}, m.get("org") or {}
    for key, want in (("name", i.get("name")), ("slug", i.get("slug"))):
        if org.get(key) and want and org[key] != want:
            errs.append(f"{MANIFEST} org.{key} is {org[key]!r} and identity.{key} is {want!r}: one name, one slug")
    return errs


def stage(root=HERE) -> str:
    """The lifecycle stage, computed by scripts/seedlife.py from evidence when the system carries it; never read from the manifest."""
    f = Path(root) / "ops/seed-lifecycle.json"
    if f.is_file():
        try:
            j = json.loads(f.read_text(encoding="utf-8"))
            s = j.get("stage") or next((v.get("stage") for v in (j.get("seeds") or {}).values() if isinstance(v, dict)), None)
            if s in LIFECYCLE:
                return s
        except (ValueError, AttributeError):
            pass
    return "unmeasured"


# --- blocks ---
def _block(name: str, body: list[str]) -> str:
    return "\n".join([f"<!-- {name}:start (generated by scripts/surfaces.py from {MANIFEST}; do not edit) -->", *body, f"<!-- {name}:end -->"]) + "\n"


def _re(name: str):
    return re.compile(rf"<!-- {name}:start[^>]*-->.*?<!-- {name}:end -->\n?", re.S)


def identity_block(i: dict) -> str:
    parent = f" It runs on [Ultrastable]({PLATFORM}/), the foundation for any autonomous system." if i.get("layer") in ("seeded-system", "tenant") else ""
    return _block("identity", [f"**{i['name']}.** {i['summary']}{parent}"])


def runs_text(r: dict) -> str:
    kind = {"worker": "Cloudflare Worker", "pages": "Cloudflare Pages project", "actions": "GitHub Actions workflow", "container": "container", "function": "function"}[r["kind"]]
    return f"{kind} `{r['name']}`" + (f", {r['how']}" if r.get("how") else "")


def live_block(i: dict) -> str:
    """The same block foundation/livelinks.py writes from the platform's registries, computed here from the manifest alone."""
    o = i.get("public_url")
    if i.get("layer") in ("template", "admin", "org-profile") and not o:
        return ""  # nothing deploys from it; a template names a running example instead (the platform writes that block)
    if not o:
        return "\n".join([LIVE_START, "## Live", "", "Not deployed yet. This repository holds the system's manifest; when its first version is deployed, this block names where it runs.",
                          "", f"Runs on [Ultrastable]({PLATFORM}/), the foundation for any autonomous system.", LIVE_END]) + "\n"
    body = ["## Live", "", f"**Running at [{o}]({o}/)**", "", "| | |", "|---|---|", f"| Health report | [{o}/health]({o}/health) |",
            f"| What it states, and the endpoint behind each statement | [{o}/claims.json]({o}/claims.json) |"]
    if i.get("runs_as"):
        body.append(f"| Runs as | {runs_text(i['runs_as'][0])} |")
    if i.get("layer") != "platform":
        body.append(f"| Platform | [Ultrastable]({PLATFORM}/), the foundation for any autonomous system · [every system running on it]({PLATFORM}/directory) |")
    else:
        body.append(f"| Every system running on it | [{PLATFORM}/directory]({PLATFORM}/directory) |")
    return "\n".join([LIVE_START, *body, LIVE_END]) + "\n"


def how_block(i: dict, st: str) -> str:
    o = i.get("public_url")
    where = (lambda path, text: f"[{text}]({o}{path})") if o else (lambda path, text: f"`{path}`")
    body = ["## How this system runs", "",
            f"**What it is.** {i['summary']}", ""]
    if i.get("loop"):
        body += [f"**The loop it closes.** {i['loop']}", ""]
    if i.get("layer") in ("seeded-system", "template", "platform"):
        body += ["**How it bootstraps.** One file, `IDEA.md`, states the idea and its system test (a loop to close, a measure that can be wrong, upkeep that never ends, "
                 "a running cost the owner accepts). `bootstrap/bootstrap.py` reads it with `ultrastable.json` and `autonomy/policy.json`, qualifies the idea, hires the roles, "
                 "writes the Worker's configuration and database, and deploys the tick Worker. No person runs a command.", ""]
    elif i.get("layer") == "tenant":
        body += [f"**How it bootstraps.** It is a tenant of the platform ([{i.get('parent') or 'ultrastable/ultrastable'}](https://github.com/{i.get('parent') or 'ultrastable/ultrastable'})): "
                 "its manifest is registered there, this repository holds its code, and the platform builds this repository's `main` into its Worker.", ""]
    if i.get("runs_as"):
        body += ["**How it runs.** " + "; ".join(runs_text(r) + (f" at {', '.join(r['routes'])}" if r.get("routes") else "") for r in i["runs_as"]) +
                 ". Work is taken, done, verified and recorded by the system's own loops on a clock; a session or a person only adds ideas.", ""]
    if i.get("layer") in ("seeded-system", "template", "platform", "tenant"):
        body += ["**How it becomes autonomous.** Two ladders, both computed from evidence the system records, never declared:", "",
                 "- ignition (read every tick, reported at " + where("/health", "/health") + "): " + " → ".join(f"`{s}`" for s in IGNITION) +
                 ". `instrumented` and above means bootstrapped; the first unmet stage is filed as its own work item.",
                 "- lifecycle (`scripts/seedlife.py`): " + " → ".join(f"`{s}`" for s in LIFECYCLE) + f". Stage at the last reading: `{st}`. "
                 "`autonomous` needs every one-year survival question answered (credentials, budget, dependencies, models, health, backups, renewal, improvement, privacy).", "",
                 "**How criticality is read.** k = verified deploys / (normalized cost + human touches), logged every tick and served at " + where("/live", "/live") +
                 " (`k_eff`, and `k_self` for deploys the system originated itself). At or above 1 with `k_self` carrying it, the system is self-sustaining.", ""]
    return _block("how", body[:-1] if body[-1] == "" else body)


def render_readme(text: str, i: dict, st: str) -> str:
    """Title, identity, Live, then the rest; How this system runs is replaced in place or appended. Running it twice changes nothing."""
    blocks = {"identity": identity_block(i), "how": how_block(i, st)}
    live = live_block(i)
    rest = text
    for name in blocks:
        rest = _re(name).sub("", rest, count=1)
    rest = LIVE_RE.sub("", rest, count=1)
    h = re.search(r"^# .*\n", rest, re.M)
    body = (rest[h.end():] if h else rest).strip("\n")
    title = h.group(0) if h else f"# {i['name']}\n"
    out = f"{title}\n{blocks['identity']}\n" + (live + "\n" if live else "") + (body + "\n\n" if body else "") + blocks["how"]
    return out


def publiccode(i: dict, st: str) -> str:
    status = {"live": "stable", "planned": "concept", "retired": "obsolete"}.get(i.get("status", "live"), "development")
    q = lambda s: json.dumps(str(s), ensure_ascii=False)  # noqa: E731  JSON strings are YAML strings
    lines = ["# Generated by scripts/surfaces.py from ultrastable.json; do not edit. https://yml.publiccode.tools/", "publiccodeYmlVersion: \"0.4\"",
             f"name: {q(i['name'])}", f"url: {q('https://github.com/' + i['repo'])}"]
    if i.get("public_url"):
        lines.append(f"landingURL: {q(i['public_url'])}")
    lines += ["platforms:", "  - web", f"developmentStatus: {status}", "softwareType: standalone/web", "legal:", f"  license: {q(i['license'])}",
              "maintenance:", "  type: internal", "localisation:", "  localisationReady: false", "  availableLanguages:", "    - en",
              "description:", "  en:", f"    shortDescription: {q(i['summary'][:150])}", f"    longDescription: {q(i['summary'])}"]
    return "\n".join(lines) + "\n"


def catalog(i: dict, st: str) -> str:
    """Backstage descriptor (backstage.io/v1alpha1): what this system is, for any software catalog that reads catalog-info.yaml. A Component
    of the one System `ultrastable`, with a `website` type when it serves a public address and `service` otherwise. STANDARDS-FIRST-1."""
    q = lambda s: json.dumps(str(s), ensure_ascii=False)  # noqa: E731  JSON strings are YAML strings
    org, name = i["repo"].split("/", 1)
    lifecycle = {"live": "production", "planned": "experimental", "retired": "deprecated"}.get(i.get("status", "live"), "experimental")
    kind = {"platform": "service", "template": "template", "admin": "documentation", "org-profile": "documentation"}.get(i.get("layer"), "website" if i.get("public_url") else "service")
    meta = re.sub(r"[^a-zA-Z0-9_.-]+", "-", i["slug"]).strip("-._")[:63] or "system"
    lines = ["# Generated by scripts/surfaces.py from ultrastable.json; do not edit. https://backstage.io/docs/features/software-catalog/descriptor-format",
             "apiVersion: backstage.io/v1alpha1", "kind: Component", "metadata:", f"  name: {meta}", f"  title: {q(i['name'])}", f"  description: {q(i['summary'])}",
             "  annotations:", f"    github.com/project-slug: {i['repo']}", f"    backstage.io/source-location: {q('url:https://github.com/' + i['repo'])}"]
    tags = [t for t in sorted(i.get("topics") or []) if re.fullmatch(r"[a-z0-9:+#]+(-[a-z0-9:+#]+)*", t) and len(t) <= 63]
    if tags:
        lines += ["  tags:"] + [f"    - {t}" for t in tags]
    links = [("Source", "https://github.com/" + i["repo"], "github")]
    if i.get("public_url"):
        u = i["public_url"]
        links = [("Live", u, "web"), ("Health report", u + "/health", "dashboard"), ("What it states", u + "/claims.json", "docs")] + links
    lines += ["  links:"] + [x for t, u, ic in links for x in (f"    - url: {q(u)}", f"      title: {q(t)}", f"      icon: {ic}")]
    lines += ["spec:", f"  type: {kind}", f"  lifecycle: {lifecycle}", f"  owner: {q('group:default/' + org)}", "  system: ultrastable"]
    parent = i.get("parent")
    if parent:
        lines += ["  dependsOn:", f"    - {q('component:default/' + parent.split('/', 1)[1])}"]
    return "\n".join(lines) + "\n"


def citation(text: str | None, i: dict) -> str:
    want = {"title": i["name"], "abstract": i["summary"], "repository-code": "https://github.com/" + i["repo"], "license": i["license"]}
    if i.get("public_url"):
        want["url"] = i["public_url"]
    if not text:
        text = "cff-version: 1.2.0\nmessage: \"If you use this work, please cite it as below.\"\ntype: software\nauthors:\n  - name: \"Ultrastable\"\n"
    for k, v in want.items():
        line = f"{k}: {json.dumps(v, ensure_ascii=False)}"
        text = re.sub(rf"^{re.escape(k)}:.*$", lambda _m: line, text, count=1, flags=re.M) if re.search(rf"^{re.escape(k)}:", text, re.M) else text.rstrip("\n") + "\n" + line + "\n"
    return text


def plan(i: dict, what="all") -> dict:
    gh = {"repo": i["repo"], "description": i["summary"], "homepage": i.get("public_url") or "", "topics": sorted(i.get("topics") or []),
          "settings": {**MERGE, "private": i["visibility"] == "private", "is_template": i.get("layer") == "template"}}
    wk = {"ultrastable": 1, "name": i["name"], "url": i.get("public_url"), "repo": "https://github.com/" + i["repo"], "license": i["license"],
          "discoverable": i["visibility"] == "public", "directory": PLATFORM + "/directory", "platform": PLATFORM}
    out = {"github": gh, "wellknown": wk}
    return out if what == "all" else {what: out[what]} if what in out else {}


def surfaces(root=HERE) -> dict:
    """{relative path: the text the manifest renders for it}."""
    root, i = Path(root), identity(root)
    st = stage(root)
    rd = root / "README.md"
    ci = root / "CITATION.cff"
    out = {"README.md": render_readme(rd.read_text(encoding="utf-8") if rd.is_file() else "", i, st),
            "publiccode.yml": publiccode(i, st),
            "CITATION.cff": citation(ci.read_text(encoding="utf-8") if ci.is_file() else None, i),
            GITHUB_PLAN: json.dumps(plan(i, "github")["github"], indent=1, ensure_ascii=False) + "\n"}
    if i.get("layer") != "platform":  # the platform repository's catalog-info.yaml lists every Worker, store and tenant and is generated there (foundation/stdgen.py)
        out["catalog-info.yaml"] = catalog(i, st)
    return out


def check(root=HERE) -> list[str]:
    errs = check_manifest(root)
    if errs:
        return errs
    for rel, want in surfaces(root).items():
        f = Path(root) / rel
        if not f.is_file():
            errs.append(f"{rel}: missing; run python3 scripts/surfaces.py --render")
        elif f.read_text(encoding="utf-8") != want:
            errs.append(f"{rel}: differs from what {MANIFEST} renders; run python3 scripts/surfaces.py --render")
    return errs


def render(root=HERE) -> list[str]:
    errs = check_manifest(root)
    if errs:
        raise SystemExit("\n".join(errs))
    wrote = []
    for rel, want in surfaces(root).items():
        f = Path(root) / rel
        if not f.is_file() or f.read_text(encoding="utf-8") != want:
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(want, encoding="utf-8")
            wrote.append(rel)
    return wrote


def main(argv=None) -> int:
    av = list(sys.argv[1:] if argv is None else argv)
    root = Path(av[av.index("--root") + 1]) if "--root" in av else HERE
    if "--validate" in av:
        errs = check_manifest(root)
        print("\n".join(errs) or f"{MANIFEST}: valid")
        return 1 if errs else 0
    if "--check" in av:
        errs = check(root)
        print("\n".join("FAIL " + e for e in errs) or "surfaces ok: every surface equals what the manifest renders")
        return 1 if errs else 0
    if "--render" in av:
        wrote = render(root)
        print("surfaces: " + (", ".join(wrote) + " written" if wrote else "nothing to change"))
        return 0
    if "--plan" in av:
        k = av.index("--plan")
        what = av[k + 1] if len(av) > k + 1 and not av[k + 1].startswith("--") else "all"
        errs = check_manifest(root)
        if errs:
            print("\n".join(errs), file=sys.stderr)
            return 1
        i = identity(root)
        if what == "publiccode":
            sys.stdout.write(publiccode(i, stage(root)))
        else:
            print(json.dumps(plan(i, what), indent=1, ensure_ascii=False))
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
