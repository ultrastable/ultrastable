#!/usr/bin/env python3
"""Rebuild MANIFEST.json/MANIFEST.md from the files here and check them against inventory.json.
Usage: python verify.py            (check only, exit 1 if anything is missing or changed)
       python verify.py --write    (regenerate the manifest)"""
import hashlib, json, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
inv = json.load(open(os.path.join(HERE, "inventory.json")))
SKIP = {"MANIFEST.json", "MANIFEST.md"}

def origin(rel):
    p = rel.split("/")
    if p[0] == "vendor":
        repo = {"qnfo-workers": "QNFO/qnfo-workers", "resume": "rwnq8/resume", "rwnq8.github.io": "rwnq8/rwnq8.github.io", "rwnq8": "rwnq8/rwnq8"}[p[1]]
        return f"{repo}@{inv['repos'][repo]['head'][:12]}:{'/'.join(p[2:])}"
    if p[0] == "patches": return "git format-patch of the merged commit named in the file name"
    if p[0] == "live-state": return "D1 qnfo-audit, read 2026-11-10"
    if p[0] == "thread": return "project thread 'Position QNFO as autonomous development platform'"
    if p[0] == "memory": return "project memory (Personal Brand project)"
    if p[0] == "library": return "project Library /mnt/project-files/" + "/".join(p[1:])
    return "written by this session"

def scan():
    out = []
    for root, _, files in os.walk(HERE):
        for f in sorted(files):
            full = os.path.join(root, f); rel = os.path.relpath(full, HERE).replace(os.sep, "/")
            if rel in SKIP or "/__pycache__/" in rel: continue
            data = open(full, "rb").read()
            out.append({"path": rel, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(), "origin": origin(rel)})
    return sorted(out, key=lambda x: x["path"])

items = scan(); have = {i["path"] for i in items}
missing = [p for p in inv["required_paths"] if p not in have]
missing += [f"patches/{p}.patch" for p in inv["patches"] if f"patches/{p}.patch" not in have]
if "--write" in sys.argv:
    json.dump({"generated_by": "verify.py", "repos": inv["repos"], "files": items}, open(os.path.join(HERE, "MANIFEST.json"), "w"), indent=1)
    with open(os.path.join(HERE, "MANIFEST.md"), "w") as m:
        m.write("# Manifest\n\nGenerated by `python verify.py --write`. Each file with its size, SHA-256 prefix and origin.\n\n")
        m.write("## Source commits\n\n| Repo | PR | Commit |\n|---|---|---|\n")
        for r, v in inv["repos"].items():
            for pr, c in v["prs"].items(): m.write(f"| {r} | [#{pr}](https://github.com/{r}/pull/{pr}) | `{c}` |\n")
        m.write("\n## Files\n\n| Path | Bytes | SHA-256 | Origin |\n|---|---:|---|---|\n")
        for i in items: m.write(f"| `{i['path']}` | {i['bytes']} | `{i['sha256'][:12]}` | {i['origin']} |\n")
else:
    try:
        man = {f["path"]: f["sha256"] for f in json.load(open(os.path.join(HERE, "MANIFEST.json")))["files"]}
    except FileNotFoundError:
        man = {}
    changed = [i["path"] for i in items if man.get(i["path"]) != i["sha256"]]
    gone = [p for p in man if p not in have]
    if changed or gone: print("manifest out of date:", changed + gone); missing += changed + gone
print(f"{len(items)} files, {len(missing)} problems")
for p in missing: print("MISSING/CHANGED", p)
sys.exit(1 if missing else 0)
