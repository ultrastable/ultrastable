// DEPLOY-ALL-1: deploys every live Worker in doctrine/topology.json that no other workflow deploys (tick, dashboard) and VERIFIES that
// the code running on Cloudflare is byte-identical to what this commit builds. Exit 1 on any mismatch.
//   node deploy/deploy-workers.mjs            deploy, then verify
//   node deploy/deploy-workers.mjs --verify   verify only (drift probe; exit 1 and print DRIFT <worker> on a mismatch)
// Needs CLOUDFLARE_API_TOKEN and CLOUDFLARE_ACCOUNT_ID. Config comes from `python3 -m foundation topology --render` (one declaration, no hand-kept wrangler files).
import { readFileSync, readdirSync, mkdirSync, appendFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
const T = process.env.CLOUDFLARE_API_TOKEN, A = process.env.CLOUDFLARE_ACCOUNT_ID;
if (!T || !A) { console.error("set CLOUDFLARE_API_TOKEN and CLOUDFLARE_ACCOUNT_ID"); process.exit(1); }
const verifyOnly = process.argv.includes("--verify");
const topo = JSON.parse(readFileSync(new URL("../doctrine/topology.json", import.meta.url), "utf8"));
// site and agents have their own deploy scripts (custom domains, probes); they are verified here too, never deployed twice.
const OWN_DEPLOY = new Set(["ultrastable-site", "ultrastable-agents"]);
const live = topo.workers.filter(w => w.state === "live" && !w.retire_candidate);
const deploy = live.filter(w => !OWN_DEPLOY.has(w.id));
const sha = (b) => createHash("sha256").update(b).digest("hex");
const sh = (cmd, args, opts = {}) => execFileSync(cmd, args, { stdio: ["ignore", "pipe", "inherit"], encoding: "utf8", ...opts });
const ROOT = new URL("..", import.meta.url).pathname;
sh("python3", ["-m", "foundation", "topology", "--render"], { cwd: ROOT });
// The tick's src/config.js is generated (bootstrap writes it per tenant) and is not in git: build it the same way, from the autonomy policy.
{ const pol = JSON.parse(readFileSync(new URL("../seed/autonomy/policy.json", import.meta.url), "utf8"));
  const cfg = { org_slug: "ultrastable", claim_ttl_minutes: 120, max_wip_per_role: 3, plus_share: 0.2, policy: { trust: pol.trust, ladder: pol.ladder, surfaces: pol.surfaces } };
  writeFileSync(new URL("../seed/worker/src/config.js", import.meta.url), "// Generated by deploy/deploy-workers.mjs from seed/autonomy/policy.json. Do not edit.\nexport default " + JSON.stringify(cfg, null, 2) + ";\n"); }
const gitsha = process.env.GITHUB_SHA || sh("git", ["rev-parse", "HEAD"], { cwd: ROOT }).trim();
// Bundle with wrangler's dry run: the files it writes are exactly what a deploy uploads.
function bundle(w) {
  const out = `/tmp/bundle-${w.id}`; mkdirSync(out, { recursive: true });
  sh("npx", ["-y", "wrangler@4", "deploy", "--dry-run", "--outdir", out, "-c", `deploy/wrangler/${w.id}.json`], { cwd: ROOT });
  const files = {}; for (const f of readdirSync(out)) if (/\.(m?js)$/.test(f)) files[f] = sha(readFileSync(`${out}/${f}`));
  return files;
}
async function liveFiles(name) {
  const r = await fetch(`https://api.cloudflare.com/client/v4/accounts/${A}/workers/scripts/${name}/content/v2`, { headers: { authorization: "Bearer " + T } });
  if (!r.ok) return null;
  const files = {};
  if ((r.headers.get("content-type") || "").startsWith("multipart/")) { for (const [k, v] of await r.formData()) files[k] = sha(Buffer.from(await v.arrayBuffer())); }
  else files[r.headers.get("cf-entrypoint") || "worker.js"] = sha(Buffer.from(await r.arrayBuffer()));
  return files;
}
const results = [];
for (const w of deploy) {
  const want = bundle(w);
  if (!verifyOnly) {
    // --keep-vars: owner-set variables (OWNER_EMAIL) survive; secrets always survive. --tag ties the deployed version to this commit.
    sh("npx", ["-y", "wrangler@4", "deploy", "-c", `deploy/wrangler/${w.id}.json`, "--keep-vars", "--tag", gitsha.slice(0, 12), "--message", "deploy-workers " + gitsha], { cwd: ROOT });
  }
  let got = null;
  for (let i = 0; i < 6; i++) { got = await liveFiles(w.id); if (got && Object.entries(want).every(([k, h]) => got[k] === h)) break; if (verifyOnly) break; await new Promise(r => setTimeout(r, 5000)); }
  const ok = !!got && Object.entries(want).every(([k, h]) => got[k] === h);
  const bad = got ? Object.keys(want).filter(k => got[k] !== want[k]) : ["(script not found)"];
  console.log(ok ? "OK    " : "DRIFT ", w.id, ok ? "live code matches " + gitsha.slice(0, 7) : "differs in " + bad.join(", "));
  results.push({ worker: w.id, ok });
  if (!verifyOnly) appendFileSync(new URL("../ops/deploys.jsonl", import.meta.url), JSON.stringify({ at: new Date().toISOString(), worker: w.id, uploaded: true, live_matches_commit: ok, sha: gitsha }) + "\n");
}
// Health: the tick must have finished a run after the deploy (the same signal /health judges).
if (!verifyOnly && results.every(r => r.ok)) console.log("deployed and verified:", results.map(r => r.worker).join(", "));
process.exit(results.every(r => r.ok) ? 0 : 1);
